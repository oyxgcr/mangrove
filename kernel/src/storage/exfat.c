static u16 exfat_le16(const u8 *p)
{
    return (u16)p[0] | (u16)p[1] << 8U;
}

static u32 exfat_le32(const u8 *p)
{
    return (u32)p[0] | (u32)p[1] << 8U | (u32)p[2] << 16U |
           (u32)p[3] << 24U;
}

static u64 exfat_le64(const u8 *p)
{
    u64 value = 0;
    for (u32 i = 0; i < 8U; i++) value |= (u64)p[i] << (i * 8U);
    return value;
}

static void exfat_put16(u8 *p, u16 value)
{
    p[0] = (u8)value;
    p[1] = (u8)(value >> 8U);
}

static void exfat_put32(u8 *p, u32 value)
{
    for (u32 i = 0; i < 4U; i++) p[i] = (u8)(value >> (i * 8U));
}

static void exfat_put64(u8 *p, u64 value)
{
    for (u32 i = 0; i < 8U; i++) p[i] = (u8)(value >> (i * 8U));
}

static bool exfat_read(exfat_fs_t *fs, u64 lba, u32 count, void *buffer)
{
    if (!fs || !fs->dev || !buffer || !count ||
        !block_device_is_live(fs->dev) || lba > fs->dev->sector_count ||
        (u64)count > fs->dev->sector_count - lba) return false;
    return block_read(fs->dev, lba, count, buffer);
}

static bool exfat_write(exfat_fs_t *fs, u64 lba, u32 count,
                        const void *buffer)
{
    if (!fs || !fs->dev || !buffer || !count ||
        !block_device_is_live(fs->dev) || lba > fs->dev->sector_count ||
        (u64)count > fs->dev->sector_count - lba) return false;
    return block_write(fs->dev, lba, count, buffer);
}

static bool exfat_add_u64(u64 left, u64 right, u64 *out)
{
    if (!out || left > ~(u64)0 - right) return false;
    *out = left + right;
    return true;
}

static bool exfat_mul_u64(u64 left, u64 right, u64 *out)
{
    if (!out || (left && right > ~(u64)0 / left)) return false;
    *out = left * right;
    return true;
}

static u32 exfat_boot_checksum_bytes(const u8 *data, usize length)
{
    u32 checksum = 0;

    if (!data) return 0;
    for (usize i = 0; i < length; i++) {
        /* VolumeFlags and PercentInUse are mutable fields and are excluded
         * from the exFAT boot checksum. */
        if (i == 106U || i == 107U || i == 112U) continue;
        checksum = (checksum >> 1U) | (checksum << 31U);
        checksum += data[i];
    }
    return checksum;
}

static bool exfat_read_boot_region(block_device_t *dev, u64 start,
                                   exfat_boot_info_t *out)
{
    u8 boot_sector[EXFAT_SECTOR_BYTES];
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 checksum_sector[EXFAT_SECTOR_BYTES];
    u8 signature[8] = { 'E','X','F','A','T',' ',' ',' ' };
    u32 checksum = 0;

    if (!dev || !out || dev->sector_size != EXFAT_SECTOR_BYTES ||
        start > dev->sector_count ||
        EXFAT_BOOT_REGION_SECTORS > dev->sector_count - start) return false;
    if (!block_read(dev, start, 1U, boot_sector) ||
        memcmp(boot_sector + 3U, signature, sizeof(signature)) != 0 ||
        boot_sector[510] != 0x55U || boot_sector[511] != 0xaaU) return false;
    for (u32 index = 0; index < 11U; index++) {
        if (!block_read(dev, start + index, 1U, sector)) return false;
        for (u32 byte = 0; byte < EXFAT_SECTOR_BYTES; byte++) {
            u32 absolute = index * EXFAT_SECTOR_BYTES + byte;
            if (absolute == 106U || absolute == 107U || absolute == 112U)
                continue;
            checksum = (checksum >> 1U) | (checksum << 31U);
            checksum += sector[byte];
        }
    }
    if (!block_read(dev, start + EXFAT_BOOT_CHECKSUM_SECTOR, 1U,
                    checksum_sector)) return false;
    for (u32 offset = 0; offset + 4U <= EXFAT_SECTOR_BYTES; offset += 4U)
        if (exfat_le32(checksum_sector + offset) != checksum) return false;

    memset(out, 0, sizeof(*out));
    out->partition_offset = exfat_le64(boot_sector + 64U);
    out->volume_length = exfat_le64(boot_sector + 72U);
    out->fat_offset = exfat_le32(boot_sector + 80U);
    out->fat_length = exfat_le32(boot_sector + 84U);
    out->heap_offset = exfat_le32(boot_sector + 88U);
    out->cluster_count = exfat_le32(boot_sector + 92U);
    out->root_cluster = exfat_le32(boot_sector + 96U);
    out->volume_serial = exfat_le32(boot_sector + 100U);
    out->revision = exfat_le16(boot_sector + 104U);
    out->volume_flags = exfat_le16(boot_sector + 106U);
    out->bytes_per_sector_shift = boot_sector[108];
    out->sectors_per_cluster_shift = boot_sector[109];
    out->fat_count = boot_sector[110];
    out->percent_in_use = boot_sector[112];

    if (out->revision < 0x0100U || out->revision > 0x0101U ||
        out->bytes_per_sector_shift != 9U ||
        out->sectors_per_cluster_shift > 11U ||
        (out->fat_count != 1U && out->fat_count != 2U) ||
        (out->fat_count == 1U && (out->volume_flags & 1U) != 0U) ||
        out->fat_offset < 24U || !out->fat_length || !out->cluster_count ||
        out->cluster_count > 0xfffffff5U || out->root_cluster < 2U ||
        out->root_cluster > out->cluster_count + 1U) return false;
    return true;
}

static bool exfat_boot_geometry_valid(block_device_t *dev,
                                      const exfat_boot_info_t *boot)
{
    u64 fat_end;
    u64 heap_bytes;
    u64 heap_end;
    u64 fat_capacity;

    if (!dev || !boot || dev->sector_size != EXFAT_SECTOR_BYTES ||
        !boot->volume_length || boot->volume_length > dev->sector_count)
        return false;
    if (!exfat_mul_u64(boot->fat_length, boot->fat_count, &fat_capacity) ||
        !exfat_add_u64(boot->fat_offset, fat_capacity, &fat_end) ||
        fat_end > dev->sector_count || boot->heap_offset < fat_end)
        return false;
    if (!exfat_mul_u64(boot->cluster_count,
                       1ULL << boot->sectors_per_cluster_shift,
                       &heap_bytes) ||
        !exfat_add_u64(boot->heap_offset, heap_bytes, &heap_end) ||
        heap_end > boot->volume_length || heap_end > dev->sector_count)
        return false;
    fat_capacity = (u64)boot->fat_length * (EXFAT_SECTOR_BYTES / 4U);
    if ((u64)boot->cluster_count + 2ULL > fat_capacity) return false;
    return true;
}

static bool exfat_read_geometry(block_device_t *dev, exfat_boot_info_t *out)
{
    exfat_boot_info_t main_boot;
    exfat_boot_info_t backup_boot;

    if (!exfat_read_boot_region(dev, EXFAT_MAIN_BOOT_LBA, &main_boot) ||
        !exfat_read_boot_region(dev, EXFAT_BACKUP_BOOT_LBA, &backup_boot) ||
        !exfat_boot_geometry_valid(dev, &main_boot) ||
        !exfat_boot_geometry_valid(dev, &backup_boot)) return false;
    /* VolumeFlags and PercentInUse are mutable boot-region fields.  Their
     * values may legitimately differ between the main and backup copies
     * after another OS has mounted and cleanly released the volume.  The
     * structural fields must still agree exactly. */
    if (main_boot.partition_offset != backup_boot.partition_offset ||
        main_boot.volume_length != backup_boot.volume_length ||
        main_boot.fat_offset != backup_boot.fat_offset ||
        main_boot.fat_length != backup_boot.fat_length ||
        main_boot.heap_offset != backup_boot.heap_offset ||
        main_boot.cluster_count != backup_boot.cluster_count ||
        main_boot.root_cluster != backup_boot.root_cluster ||
        main_boot.volume_serial != backup_boot.volume_serial ||
        main_boot.revision != backup_boot.revision ||
        main_boot.bytes_per_sector_shift != backup_boot.bytes_per_sector_shift ||
        main_boot.sectors_per_cluster_shift !=
            backup_boot.sectors_per_cluster_shift ||
        main_boot.fat_count != backup_boot.fat_count) {
        return false;
    }
    if (out) *out = main_boot;
    return true;
}

static bool exfat_set_volume_dirty(exfat_fs_t *fs, bool dirty)
{
    u16 flags;

    if (!fs || !fs->dev || !block_device_is_live(fs->dev)) return false;
    flags = fs->boot.volume_flags;
    if (dirty) flags |= 0x0002U;
    else flags &= (u16)~0x0002U;
    if (flags == fs->boot.volume_flags) return true;
    /* VolumeFlags is excluded from the boot-region checksum.  Keep the main
     * and backup copies synchronized, and do not proceed with a metadata
     * mutation if either protected write fails. */
    for (u64 base = EXFAT_MAIN_BOOT_LBA;
         base <= EXFAT_BACKUP_BOOT_LBA; base += EXFAT_BACKUP_BOOT_LBA) {
        u8 sector[EXFAT_SECTOR_BYTES];
        if (!exfat_read(fs, base, 1U, sector)) return false;
        exfat_put16(sector + 106U, flags);
        if (!exfat_write(fs, base, 1U, sector)) return false;
    }
    fs->boot.volume_flags = flags;
    return true;
}

static u64 exfat_cluster_lba(const exfat_fs_t *fs, u32 cluster)
{
    u64 offset;
    if (!fs || cluster < EXFAT_CLUSTER_FIRST ||
        cluster > fs->boot.cluster_count + 1U ||
        !exfat_mul_u64((u64)cluster - 2ULL, fs->sectors_per_cluster,
                       &offset) ||
        !exfat_add_u64(fs->boot.heap_offset, offset, &offset)) return ~(u64)0;
    return offset;
}

static bool exfat_fat_get(exfat_fs_t *fs, u32 cluster, u32 *out_value)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 byte_offset;
    u64 lba;
    u32 offset;

    if (!fs || !out_value || cluster > fs->boot.cluster_count + 1U ||
        !exfat_mul_u64(cluster, 4ULL, &byte_offset)) return false;
    lba = (u64)fs->boot.fat_offset + fs->active_fat * fs->boot.fat_length +
          byte_offset / EXFAT_SECTOR_BYTES;
    offset = (u32)(byte_offset % EXFAT_SECTOR_BYTES);
    if (offset > EXFAT_SECTOR_BYTES - 4U || !exfat_read(fs, lba, 1U, sector))
        return false;
    *out_value = exfat_le32(sector + offset);
    return true;
}

static bool exfat_fat_set(exfat_fs_t *fs, u32 cluster, u32 value)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 byte_offset;
    u32 offset;

    if (!fs || cluster < EXFAT_CLUSTER_FIRST ||
        cluster > fs->boot.cluster_count + 1U ||
        !exfat_mul_u64(cluster, 4ULL, &byte_offset)) return false;
    offset = (u32)(byte_offset % EXFAT_SECTOR_BYTES);
    if (offset > EXFAT_SECTOR_BYTES - 4U) return false;
    if (!exfat_read(fs, (u64)fs->boot.fat_offset +
                    fs->active_fat * fs->boot.fat_length +
                    byte_offset / EXFAT_SECTOR_BYTES, 1U, sector)) return false;
    exfat_put32(sector + offset, value);
    for (u32 fat = 0; fat < fs->boot.fat_count; fat++) {
        u64 lba = (u64)fs->boot.fat_offset + fat * fs->boot.fat_length +
                  byte_offset / EXFAT_SECTOR_BYTES;
        if (!exfat_write(fs, lba, 1U, sector)) return false;
    }
    return true;
}

static bool exfat_chain_cluster(exfat_fs_t *fs, u32 first, bool no_fat,
                                u64 index, u32 *out_cluster)
{
    u32 cluster = first;

    if (!fs || !out_cluster || first < 2U ||
        first > fs->boot.cluster_count + 1U ||
        index > EXFAT_MAX_DIRECTORY_CLUSTERS) return false;
    if (no_fat) {
        if (index > fs->boot.cluster_count + 1U - first) return false;
        *out_cluster = first + (u32)index;
        return true;
    }
    for (u64 step = 0; step < index; step++) {
        u32 next;
        if (!exfat_fat_get(fs, cluster, &next) || next < 2U ||
            next > fs->boot.cluster_count + 1U ||
            next >= EXFAT_CLUSTER_EOC_MIN)
            return false;
        cluster = next;
    }
    *out_cluster = cluster;
    return true;
}

static bool exfat_dir_byte_read(exfat_fs_t *fs, u32 first, bool no_fat,
                                u64 offset, void *buffer, usize length)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 *out = (u8 *)buffer;
    u64 limit;

    if (!fs || !buffer || !length ||
        !exfat_mul_u64(fs->boot.cluster_count,
                       fs->cluster_bytes, &limit) || offset > limit ||
        (u64)length > limit - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within_cluster = offset % fs->cluster_bytes;
        u64 sector_index = within_cluster / EXFAT_SECTOR_BYTES;
        u32 within_sector = (u32)(within_cluster % EXFAT_SECTOR_BYTES);
        u32 cluster;
        usize amount = EXFAT_SECTOR_BYTES - within_sector;
        u64 lba;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_chain_cluster(fs, first, no_fat, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(out, sector + within_sector, amount);
        out += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

static bool exfat_dir_byte_write(exfat_fs_t *fs, u32 first, bool no_fat,
                                 u64 offset, const void *buffer, usize length)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    const u8 *input = (const u8 *)buffer;
    u64 limit;

    if (!fs || !buffer || !length ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &limit) ||
        offset > limit || (u64)length > limit - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within_cluster = offset % fs->cluster_bytes;
        u64 sector_index = within_cluster / EXFAT_SECTOR_BYTES;
        u32 within_sector = (u32)(within_cluster % EXFAT_SECTOR_BYTES);
        u32 cluster;
        usize amount = EXFAT_SECTOR_BYTES - within_sector;
        u64 lba;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_chain_cluster(fs, first, no_fat, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(sector + within_sector, input, amount);
        if (!exfat_write(fs, lba, 1U, sector)) return false;
        input += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

static u32 exfat_upcase_checksum(const u8 *data, usize length)
{
    u32 checksum = 0;

    if (!data) return 0;
    for (usize i = 0; i < length; i++) {
        checksum = (checksum >> 1U) | (checksum << 31U);
        checksum += data[i];
    }
    return checksum;
}

static bool exfat_upcase_decode_valid(const u8 *data, usize length)
{
    u32 codepoint = 0;
    usize offset = 0;

    if (!data || !length || (length & 1U)) return false;
    while (offset + 2U <= length && codepoint < 0x10000U) {
        u16 value = exfat_le16(data + offset);
        offset += 2U;
        if (value == 0xffffU) {
            u32 skip;
            if (offset + 2U > length) {
                /* The standard table uses a final marker for the remaining
                 * identity mappings. */
                return codepoint <= 0x10000U;
            }
            skip = (u32)exfat_le16(data + offset) + 1U;
            offset += 2U;
            if (skip > 0x10000U - codepoint) return false;
            codepoint += skip;
        } else {
            if (codepoint >= 0x10000U) return false;
            codepoint++;
        }
    }
    return codepoint == 0x10000U;
}

static u16 exfat_upcase_unit(const exfat_fs_t *fs, u16 input)
{
    u32 codepoint = 0;
    usize offset = 0;

    if (!fs || !fs->upcase) return input;
    while (offset + 2U <= fs->upcase_length && codepoint <= input) {
        u16 value = exfat_le16(fs->upcase + offset);
        offset += 2U;
        if (value == 0xffffU) {
            u32 skip;
            if (offset + 2U > fs->upcase_length) return input;
            skip = (u32)exfat_le16(fs->upcase + offset) + 1U;
            offset += 2U;
            if (input < codepoint + skip) return input;
            codepoint += skip;
        } else {
            if (codepoint == input) return value;
            codepoint++;
        }
    }
    return input;
}

static bool exfat_utf8_decode_one(const u8 *input, usize length, usize *offset,
                                  u32 *out_codepoint)
{
    usize at;
    u8 lead;
    u32 value;
    u32 minimum;
    u32 count;

    if (!input || !offset || !out_codepoint || *offset >= length) return false;
    at = *offset;
    lead = input[at++];
    if (lead < 0x80U) {
        value = lead; minimum = 0; count = 1;
    } else if (lead >= 0xc2U && lead <= 0xdfU) {
        value = lead & 0x1fU; minimum = 0x80U; count = 2;
    } else if (lead >= 0xe0U && lead <= 0xefU) {
        value = lead & 0x0fU; minimum = 0x800U; count = 3;
    } else if (lead >= 0xf0U && lead <= 0xf4U) {
        value = lead & 7U; minimum = 0x10000U; count = 4;
    } else return false;
    if (at + count - 1U > length) return false;
    for (u32 i = 1U; i < count; i++) {
        u8 byte = input[at++];
        if ((byte & 0xc0U) != 0x80U) return false;
        value = (value << 6U) | (byte & 0x3fU);
    }
    if (value < minimum || value > 0x10ffffU ||
        (value >= 0xd800U && value <= 0xdfffU)) return false;
    *offset = at;
    *out_codepoint = value;
    return true;
}

static bool exfat_name_codepoint_allowed(u32 value)
{
    if (value == 0U || value < 0x20U ||
        (value >= 0x7fU && value <= 0x9fU)) return false;
    return value != '<' && value != '>' && value != ':' && value != '"' &&
           value != '/' && value != '\\' && value != '|' && value != '?' &&
           value != '*';
}

static bool exfat_utf8_to_utf16(const char *input, u16 *output,
                                u16 *out_units, bool label)
{
    usize length;
    usize offset = 0;
    u16 units = 0;
    bool content = false;
    u32 first = 0;
    u32 last = 0;

    if (!input || !output || !out_units ||
        (length = strlen(input)) > (label ? 255U : 255U)) return false;
    while (offset < length) {
        u32 value;
        if (!exfat_utf8_decode_one((const u8 *)input, length, &offset,
                                   &value) || !exfat_name_codepoint_allowed(value))
            return false;
        if (!first) first = value;
        last = value;
        if (value != ' ' && value != '\t') content = true;
        if (value <= 0xffffU) {
            if (units >= EXFAT_MAX_NAME_UNITS) return false;
            output[units++] = (u16)value;
        } else {
            if (units > EXFAT_MAX_NAME_UNITS - 2U) return false;
            value -= 0x10000U;
            output[units++] = (u16)(0xd800U | (value >> 10U));
            output[units++] = (u16)(0xdc00U | (value & 0x3ffU));
        }
    }
    if (label && units > 11U) return false;
    if (label && units && (!content || first == ' ' || last == ' ')) return false;
    *out_units = units;
    return true;
}

static bool exfat_utf16_to_utf8(const u16 *input, u16 units, char *output,
                                usize capacity)
{
    usize position = 0;

    if (!input || !output || !capacity || units > EXFAT_MAX_NAME_UNITS)
        return false;
    for (u16 i = 0; i < units; i++) {
        u32 value = input[i];
        usize encoded;
        if (value >= 0xd800U && value <= 0xdbffU) {
            u16 low;
            if (i + 1U >= units || (low = input[++i]) < 0xdc00U ||
                low > 0xdfffU) return false;
            value = 0x10000U + ((value - 0xd800U) << 10U) +
                    (low - 0xdc00U);
        } else if (value >= 0xdc00U && value <= 0xdfffU) return false;
        if (value < 0x80U) encoded = 1U;
        else if (value < 0x800U) encoded = 2U;
        else if (value < 0x10000U) encoded = 3U;
        else encoded = 4U;
        if (position > capacity - 1U - encoded) return false;
        if (encoded == 1U) output[position++] = (char)value;
        else if (encoded == 2U) {
            output[position++] = (char)(0xc0U | (value >> 6U));
            output[position++] = (char)(0x80U | (value & 0x3fU));
        } else if (encoded == 3U) {
            output[position++] = (char)(0xe0U | (value >> 12U));
            output[position++] = (char)(0x80U | ((value >> 6U) & 0x3fU));
            output[position++] = (char)(0x80U | (value & 0x3fU));
        } else {
            output[position++] = (char)(0xf0U | (value >> 18U));
            output[position++] = (char)(0x80U | ((value >> 12U) & 0x3fU));
            output[position++] = (char)(0x80U | ((value >> 6U) & 0x3fU));
            output[position++] = (char)(0x80U | (value & 0x3fU));
        }
    }
    if (position >= capacity) return false;
    output[position] = '\0';
    return true;
}

static bool exfat_bitmap_bit(exfat_fs_t *fs, u32 cluster, bool *out_used)
{
    u8 byte;
    u64 bit;

    if (!fs || !out_used || cluster < 2U ||
        cluster > fs->boot.cluster_count + 1U) return false;
    bit = (u64)cluster - 2ULL;
    if (bit / 8ULL >= fs->bitmap_length ||
        !exfat_dir_byte_read(fs, fs->bitmap_cluster, fs->bitmap_no_fat,
                             bit / 8ULL, &byte, 1U)) return false;
    *out_used = (byte & (1U << (bit % 8ULL))) != 0U;
    return true;
}

static bool exfat_bitmap_set(exfat_fs_t *fs, u32 cluster, bool used)
{
    u8 byte;
    u64 bit;

    if (!fs || cluster < 2U || cluster > fs->boot.cluster_count + 1U)
        return false;
    bit = (u64)cluster - 2ULL;
    if (bit / 8ULL >= fs->bitmap_length ||
        !exfat_dir_byte_read(fs, fs->bitmap_cluster, fs->bitmap_no_fat,
                             bit / 8ULL, &byte, 1U)) return false;
    if (used) byte |= (u8)(1U << (bit % 8ULL));
    else byte &= (u8)~(1U << (bit % 8ULL));
    return exfat_dir_byte_write(fs, fs->bitmap_cluster, fs->bitmap_no_fat,
                                bit / 8ULL, &byte, 1U);
}

/* The allocation bitmap is itself an ordinary exFAT system stream.  Keep its
 * addressing behind the same chain validation used for every other stream;
 * formatter-created volumes use the normal contiguous form, but imported
 * media need not. */
static bool exfat_bitmap_byte_lba(exfat_fs_t *fs, u64 byte, u64 *out_lba)
{
    u32 cluster;
    u64 cluster_index;
    u64 within;
    u64 lba;

    if (!fs || !out_lba || byte >= fs->bitmap_length ||
        !fs->cluster_bytes) return false;
    cluster_index = byte / fs->cluster_bytes;
    within = byte % fs->cluster_bytes;
    if (!exfat_chain_cluster(fs, fs->bitmap_cluster, fs->bitmap_no_fat,
                             cluster_index, &cluster) ||
        (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
        !exfat_add_u64(lba, within / EXFAT_SECTOR_BYTES, out_lba))
        return false;
    return true;
}

static bool exfat_bitmap_set_range(exfat_fs_t *fs, u32 first, u64 count,
                                   bool used)
{
    u64 first_bit;
    u64 last_bit;
    u64 first_byte;
    u64 last_byte;
    u64 sector_byte;
    u8 sector[EXFAT_SECTOR_BYTES];

    if (!fs || first < EXFAT_CLUSTER_FIRST || !count ||
        count > fs->boot.cluster_count + 1ULL - first) return false;
    first_bit = (u64)first - EXFAT_CLUSTER_FIRST;
    if (count - 1ULL > ~(u64)0 - first_bit) return false;
    last_bit = first_bit + count - 1ULL;
    first_byte = first_bit / 8ULL;
    last_byte = last_bit / 8ULL;
    if (last_byte >= fs->bitmap_length) return false;
    sector_byte = first_byte & ~(u64)(EXFAT_SECTOR_BYTES - 1U);
    for (u64 byte = sector_byte;; byte += EXFAT_SECTOR_BYTES) {
        u64 lba;
        u64 sector_byte_end;
        u32 begin;
        u32 end;

        if (!exfat_bitmap_byte_lba(fs, byte, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        sector_byte_end = byte + EXFAT_SECTOR_BYTES - 1ULL;
        begin = byte == first_byte ? (u32)(first_bit % 8ULL) : 0U;
        end = sector_byte_end >= last_byte ? (u32)(last_bit % 8ULL) : 7U;
        for (u32 at = 0; at < EXFAT_SECTOR_BYTES; at++) {
            u64 this_byte = byte + at;
            u32 bit_begin;
            u32 bit_end;
            u8 mask;

            if (this_byte < first_byte || this_byte > last_byte) continue;
            bit_begin = this_byte == first_byte ? begin : 0U;
            bit_end = this_byte == last_byte ? end : 7U;
            mask = (u8)(((1U << (bit_end - bit_begin + 1U)) - 1U) <<
                        bit_begin);
            if (used) sector[at] |= mask;
            else sector[at] &= (u8)~mask;
        }
        if (!exfat_write(fs, lba, 1U, sector)) return false;
        if (sector_byte_end >= last_byte) break;
        if (byte > ~(u64)0 - EXFAT_SECTOR_BYTES) return false;
    }
    return true;
}

static bool exfat_find_free_run(exfat_fs_t *fs, u64 count, u32 *out_first)
{
    u64 run = 0;
    u32 run_first = 0;
    u64 clusters;
    u64 bitmap_bytes;
    u8 sector[EXFAT_SECTOR_BYTES];

    if (!fs || !out_first || !count || count > fs->boot.cluster_count)
        return false;
    clusters = fs->boot.cluster_count;
    bitmap_bytes = (clusters + 7ULL) / 8ULL;
    if (bitmap_bytes > fs->bitmap_length) return false;
    for (u64 byte = 0; byte < bitmap_bytes; byte += EXFAT_SECTOR_BYTES) {
        u64 lba;
        u32 bytes = bitmap_bytes - byte > EXFAT_SECTOR_BYTES ?
            EXFAT_SECTOR_BYTES : (u32)(bitmap_bytes - byte);

        if (!exfat_bitmap_byte_lba(fs, byte, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        for (u32 at = 0; at < bytes; at++) {
            for (u32 bit = 0; bit < 8U; bit++) {
                u64 index = (byte + at) * 8ULL + bit;
                u32 cluster;

                if (index >= clusters) break;
                cluster = EXFAT_CLUSTER_FIRST + (u32)index;
                if ((sector[at] & (1U << bit)) == 0U) {
                    if (!run) run_first = cluster;
                    if (++run == count) {
                        *out_first = run_first;
                        return true;
                    }
                } else run = 0;
            }
        }
    }
    return false;
}

static bool exfat_bitmap_range_unused(exfat_fs_t *fs, u32 first, u64 count)
{
    u64 first_bit;
    u64 last_bit;
    u64 first_byte;
    u64 last_byte;
    u64 sector_byte;
    u8 sector[EXFAT_SECTOR_BYTES];

    if (!fs || first < EXFAT_CLUSTER_FIRST || !count ||
        count > fs->boot.cluster_count + 1ULL - first) return false;
    first_bit = (u64)first - EXFAT_CLUSTER_FIRST;
    if (count - 1ULL > ~(u64)0 - first_bit) return false;
    last_bit = first_bit + count - 1ULL;
    first_byte = first_bit / 8ULL;
    last_byte = last_bit / 8ULL;
    if (last_byte >= fs->bitmap_length) return false;
    sector_byte = first_byte & ~(u64)(EXFAT_SECTOR_BYTES - 1U);
    for (u64 byte = sector_byte;; byte += EXFAT_SECTOR_BYTES) {
        u64 lba;
        u64 sector_byte_end;

        if (!exfat_bitmap_byte_lba(fs, byte, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        sector_byte_end = byte + EXFAT_SECTOR_BYTES - 1ULL;
        for (u32 at = 0; at < EXFAT_SECTOR_BYTES; at++) {
            u64 this_byte = byte + at;
            u32 bit_begin;
            u32 bit_end;
            u8 mask;

            if (this_byte < first_byte || this_byte > last_byte) continue;
            bit_begin = this_byte == first_byte ?
                (u32)(first_bit % 8ULL) : 0U;
            bit_end = this_byte == last_byte ?
                (u32)(last_bit % 8ULL) : 7U;
            mask = (u8)(((1U << (bit_end - bit_begin + 1U)) - 1U) <<
                        bit_begin);
            if (sector[at] & mask) return false;
        }
        if (sector_byte_end >= last_byte) break;
        if (byte > ~(u64)0 - EXFAT_SECTOR_BYTES) return false;
    }
    return true;
}

static bool exfat_read_system_entries(exfat_fs_t *fs)
{
    u64 maximum;
    u8 entry[EXFAT_ENTRY_BYTES];
    bool bitmap_found = false;
    bool upcase_found = false;
    bool label_found = false;

    if (!fs || !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes,
                              &maximum)) return false;
    for (u64 offset = 0; offset + EXFAT_ENTRY_BYTES <= maximum;
         offset += EXFAT_ENTRY_BYTES) {
        u8 type;
        if (!exfat_dir_byte_read(fs, fs->root_cluster, false, offset,
                                 entry, sizeof(entry))) return false;
        type = entry[0];
        if (type == EXFAT_ENTRY_END) break;
        if (type == EXFAT_ENTRY_BITMAP) {
            if (bitmap_found) return false;
            fs->bitmap_cluster = exfat_le32(entry + 20U);
            fs->bitmap_length = exfat_le64(entry + 24U);
            fs->bitmap_no_fat = true;
            bitmap_found = true;
        } else if (type == EXFAT_ENTRY_UPCASE) {
            if (upcase_found) return false;
            fs->upcase_checksum = exfat_le32(entry + 4U);
            fs->upcase_cluster = exfat_le32(entry + 20U);
            fs->upcase_length = exfat_le64(entry + 24U);
            fs->upcase_no_fat = true;
            upcase_found = true;
        } else if (type == EXFAT_ENTRY_LABEL) {
            u16 units = entry[1];
            u16 values[11];
            if (label_found) return false;
            if (units > 11U) return false;
            for (u16 i = 0; i < units; i++)
                values[i] = exfat_le16(entry + 2U + (u32)i * 2U);
            if (!exfat_utf16_to_utf8(values, units, fs->label,
                                     sizeof(fs->label))) return false;
            label_found = true;
        } else if (type == EXFAT_ENTRY_FILE) {
            u8 secondary = entry[1];
            if (secondary > EXFAT_MAX_SECONDARY ||
                offset > maximum - (u64)(secondary + 1U) * EXFAT_ENTRY_BYTES)
                return false;
            offset += (u64)secondary * EXFAT_ENTRY_BYTES;
        }
    }
    if (!bitmap_found || !upcase_found || fs->bitmap_cluster < 2U ||
        fs->upcase_cluster < 2U || !fs->bitmap_length || !fs->upcase_length ||
        fs->bitmap_length < ((u64)fs->boot.cluster_count + 7ULL) / 8ULL ||
        fs->upcase_length > EXFAT_MAX_UPCASE_BYTES ||
        fs->bitmap_length > (u64)fs->boot.cluster_count * fs->cluster_bytes)
        return false;
    return true;
}

static bool exfat_load_upcase(exfat_fs_t *fs)
{
    if (!fs || !fs->upcase_length || fs->upcase_length > EXFAT_MAX_UPCASE_BYTES ||
        fs->upcase_length > (u64)(usize)-1) return false;
    fs->upcase = (u8 *)kmalloc((usize)fs->upcase_length);
    if (!fs->upcase ||
        !exfat_dir_byte_read(fs, fs->upcase_cluster, fs->upcase_no_fat, 0,
                             fs->upcase, (usize)fs->upcase_length) ||
        exfat_upcase_checksum(fs->upcase, (usize)fs->upcase_length) !=
            fs->upcase_checksum ||
        !exfat_upcase_decode_valid(fs->upcase, (usize)fs->upcase_length)) {
        kfree(fs->upcase);
        fs->upcase = NULL;
        return false;
    }
    return true;
}

static void exfat_free_state(exfat_fs_t *fs)
{
    if (!fs) return;
    kfree(fs->upcase);
    fs->upcase = NULL;
    kfree(fs);
}

static exfat_fs_t *exfat_new_state(block_device_t *dev)
{
    exfat_fs_t *fs;
    exfat_boot_info_t boot;

    if (!dev || !exfat_read_geometry(dev, &boot)) return NULL;
    fs = (exfat_fs_t *)kmalloc(sizeof(*fs));
    if (!fs) return NULL;
    memset(fs, 0, sizeof(*fs));
    fs->dev = dev;
    fs->boot = boot;
    fs->sector_size = EXFAT_SECTOR_BYTES;
    fs->sectors_per_cluster = 1U << boot.sectors_per_cluster_shift;
    if (boot.bytes_per_sector_shift >= 32U - boot.sectors_per_cluster_shift) {
        kfree(fs);
        return NULL;
    }
    fs->cluster_bytes = 1U <<
        (boot.bytes_per_sector_shift + boot.sectors_per_cluster_shift);
    fs->active_fat = boot.volume_flags & 1U;
    fs->root_cluster = boot.root_cluster;
    if (fs->cluster_bytes > EXFAT_MAX_CLUSTER_BYTES ||
        !exfat_read_system_entries(fs) || !exfat_load_upcase(fs)) {
        exfat_free_state(fs);
        return NULL;
    }
    return fs;
}

static bool exfat_probe(block_device_t *dev)
{
    exfat_fs_t *fs = exfat_new_state(dev);
    if (!fs) return false;
    exfat_free_state(fs);
    return true;
}

static bool exfat_read_label_internal(block_device_t *dev, char *out,
                                      usize capacity)
{
    exfat_fs_t *fs;
    bool present;

    if (!out || capacity < 2U) return false;
    out[0] = '\0';
    fs = exfat_new_state(dev);
    if (!fs) return false;
    present = fs->label[0] != '\0' && strlen(fs->label) < capacity;
    if (present) strcpy(out, fs->label);
    exfat_free_state(fs);
    return present;
}

static u64 exfat_entry_checksum(const u8 *set, u32 count)
{
    u16 checksum = 0;
    u32 bytes;

    if (!set || !count) return 0;
    if (count > ~(u32)0 / EXFAT_ENTRY_BYTES) return 0;
    bytes = count * EXFAT_ENTRY_BYTES;
    /* The exFAT checksum covers every byte in the set except the two-byte
     * checksum field in the primary file entry (the first entry).  The
     * excluded bytes are skipped entirely, including the rotate step. */
    for (u32 index = 0; index < bytes; index++) {
        u8 value;
        if (index == 2U || index == 3U) continue;
        value = set[index];
        checksum = (u16)(((checksum & 1U) ? 0x8000U : 0U) |
                         (checksum >> 1U));
        checksum = (u16)(checksum + value);
    }
    return checksum;
}

static u16 exfat_name_hash(const exfat_fs_t *fs, const u16 *name, u16 units)
{
    u16 hash = 0;
    if (!fs || !name) return 0;
    for (u16 i = 0; i < units; i++) {
        u16 value = exfat_upcase_unit(fs, name[i]);
        hash = (u16)(((hash & 1U) ? 0x8000U : 0U) | (hash >> 1U));
        hash = (u16)(hash + (value & 0xffU));
        hash = (u16)(((hash & 1U) ? 0x8000U : 0U) | (hash >> 1U));
        hash = (u16)(hash + (value >> 8U));
    }
    return hash;
}

static bool exfat_entry_set_read(exfat_fs_t *fs, u32 parent_cluster,
                                 bool parent_no_fat, u64 offset,
                                 exfat_entry_info_t *out)
{
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u8 secondary;
    u16 units = 0;
    u32 expected_name_entries;

    if (!fs || !out || offset & (EXFAT_ENTRY_BYTES - 1U) ||
        !exfat_dir_byte_read(fs, parent_cluster, parent_no_fat, offset,
                             set, EXFAT_ENTRY_BYTES) ||
        set[0] != EXFAT_ENTRY_FILE) return false;
    secondary = set[1];
    if (secondary < 2U || secondary > EXFAT_MAX_SECONDARY ||
        !exfat_dir_byte_read(fs, parent_cluster, parent_no_fat, offset,
                             set, (secondary + 1U) * EXFAT_ENTRY_BYTES))
        return false;
    if (exfat_entry_checksum(set, secondary + 1U) != exfat_le16(set + 2U))
        return false;
    if (set[EXFAT_ENTRY_BYTES] != EXFAT_ENTRY_STREAM ||
        set[EXFAT_ENTRY_BYTES + 3U] > EXFAT_MAX_NAME_UNITS) return false;
    expected_name_entries = (set[EXFAT_ENTRY_BYTES + 3U] + 14U) / 15U;
    if (secondary != expected_name_entries + 1U) return false;
    for (u32 i = 0; i < expected_name_entries; i++) {
        u8 *entry = set + (2U + i) * EXFAT_ENTRY_BYTES;
        if (entry[0] != EXFAT_ENTRY_NAME) return false;
        for (u32 j = 0; j < 15U && units < EXFAT_MAX_NAME_UNITS; j++)
            out->name_units[units++] = exfat_le16(entry + 2U + j * 2U);
    }
    out->name_length = set[EXFAT_ENTRY_BYTES + 3U];
    if (units < out->name_length ||
        !exfat_utf16_to_utf8(out->name_units, out->name_length, out->name,
                             sizeof(out->name))) return false;
    if (exfat_name_hash(fs, out->name_units, out->name_length) !=
        exfat_le16(set + EXFAT_ENTRY_BYTES + 4U)) return false;
    memset(out, 0, sizeof(*out));
    /* The conversion above filled fields that must survive the clear. */
    out->name_length = set[EXFAT_ENTRY_BYTES + 3U];
    for (u16 i = 0; i < out->name_length; i++) {
        u32 entry = 2U + i / 15U;
        u32 at = i % 15U;
        out->name_units[i] = exfat_le16(set + entry * EXFAT_ENTRY_BYTES +
                                         2U + at * 2U);
    }
    if (!exfat_utf16_to_utf8(out->name_units, out->name_length, out->name,
                             sizeof(out->name))) return false;
    out->entry_offset = offset;
    out->parent_cluster = parent_cluster;
    out->parent_no_fat_chain = parent_no_fat;
    out->entry_count = secondary + 1U;
    out->attributes = exfat_le16(set + 4U);
    out->stream_flags = exfat_le16(set + EXFAT_ENTRY_BYTES + 1U);
    out->valid_data_length = exfat_le64(set + EXFAT_ENTRY_BYTES + 8U);
    out->first_cluster = exfat_le32(set + EXFAT_ENTRY_BYTES + 20U);
    out->data_length = exfat_le64(set + EXFAT_ENTRY_BYTES + 24U);
    if (out->valid_data_length > out->data_length ||
        ((out->data_length || out->valid_data_length) &&
         (out->first_cluster < 2U ||
          out->first_cluster > fs->boot.cluster_count + 1U))) return false;
    return true;
}

static bool exfat_directory_capacity(exfat_fs_t *fs, u32 first,
                                     bool no_fat, u64 *out_bytes)
{
    u64 clusters = 0;
    u32 cluster = first;

    if (!fs || !out_bytes || first < 2U) return false;
    for (;;) {
        u32 next;
        if (++clusters > fs->boot.cluster_count) return false;
        if (!exfat_mul_u64(clusters, fs->cluster_bytes, out_bytes)) return false;
        if (no_fat) {
            if (first > fs->boot.cluster_count + 1U - clusters) return false;
            return true;
        }
        if (!exfat_fat_get(fs, cluster, &next)) return false;
        if (next >= EXFAT_CLUSTER_EOC_MIN) return true;
        if (next < 2U || next > fs->boot.cluster_count + 1U) return false;
        cluster = next;
    }
}

static bool exfat_zero_cluster(exfat_fs_t *fs, u32 cluster)
{
    u8 zero[EXFAT_SECTOR_BYTES * 8U];
    u64 lba;

    if (!fs || (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0) return false;
    memset(zero, 0, sizeof(zero));
    for (u32 i = 0; i < fs->sectors_per_cluster;) {
        u32 batch = fs->sectors_per_cluster - i;
        if (batch > 8U) batch = 8U;
        if (!exfat_write(fs, lba + i, batch, zero)) return false;
        i += batch;
    }
    return true;
}

static bool exfat_zero_cluster_run(exfat_fs_t *fs, u32 first, u64 count)
{
    u8 zero[EXFAT_SECTOR_BYTES * 8U];
    u64 lba;
    u64 sectors;

    if (!fs || first < EXFAT_CLUSTER_FIRST || !count ||
        count > fs->boot.cluster_count + 1ULL - first ||
        !exfat_mul_u64(count, fs->sectors_per_cluster, &sectors) ||
        (lba = exfat_cluster_lba(fs, first)) == ~(u64)0 ||
        sectors > fs->dev->sector_count - lba) return false;
    memset(zero, 0, sizeof(zero));
    while (sectors) {
        u32 batch = sectors > 8ULL ? 8U : (u32)sectors;
        if (!exfat_write(fs, lba, batch, zero)) return false;
        lba += batch;
        sectors -= batch;
    }
    return true;
}

static bool exfat_allocate_contiguous_run(exfat_fs_t *fs, u64 count,
                                          u32 *out_first)
{
    u32 first;

    if (!fs || !out_first || !count ||
        !exfat_find_free_run(fs, count, &first)) return false;
    if (!exfat_bitmap_set_range(fs, first, count, true)) return false;
    if (!exfat_zero_cluster_run(fs, first, count)) {
        (void)exfat_bitmap_set_range(fs, first, count, false);
        return false;
    }
    *out_first = first;
    return true;
}

static bool exfat_alloc_cluster(exfat_fs_t *fs, u32 *out_cluster)
{
    if (!fs || !out_cluster) return false;
    for (u32 cluster = 2U; cluster <= fs->boot.cluster_count + 1U; cluster++) {
        bool used;
        if (!exfat_bitmap_bit(fs, cluster, &used)) return false;
        if (used) continue;
        if (!exfat_bitmap_set(fs, cluster, true) ||
            !exfat_fat_set(fs, cluster, EXFAT_CLUSTER_EOC) ||
            !exfat_zero_cluster(fs, cluster)) {
            (void)exfat_bitmap_set(fs, cluster, false);
            return false;
        }
        *out_cluster = cluster;
        return true;
    }
    return false;
}

static bool exfat_free_chain(exfat_fs_t *fs, u32 first, bool no_fat,
                             u64 byte_length)
{
    u64 count;
    u32 cluster = first;
    bool ended = false;

    if (!fs || first < 2U) return true;
    if (no_fat) {
        if (byte_length > ~(u64)0 - (fs->cluster_bytes - 1ULL))
            return false;
        count = (byte_length + fs->cluster_bytes - 1ULL) /
                fs->cluster_bytes;
        if (!count) count = 1U;
    } else {
        count = fs->boot.cluster_count;
    }
    /* Validate the complete chain before changing allocation metadata.  A
     * corrupt loop or out-of-range link must not result in a partially freed
     * file that is harder to diagnose or recover. */
    if (no_fat) {
        if (count > fs->boot.cluster_count + 1U - first) return false;
        ended = true;
    } else {
        for (u64 step = 0; step < count; step++) {
            u32 next;
            if (cluster < EXFAT_CLUSTER_FIRST ||
                cluster > fs->boot.cluster_count + 1U ||
                !exfat_fat_get(fs, cluster, &next)) return false;
            if (next >= EXFAT_CLUSTER_EOC_MIN) {
                ended = true;
                break;
            }
            if (next < EXFAT_CLUSTER_FIRST ||
                next > fs->boot.cluster_count + 1U) return false;
            cluster = next;
        }
        if (!ended) return false;
    }
    cluster = first;
    for (u64 step = 0; step < count; step++) {
        u32 next = EXFAT_CLUSTER_EOC;
        if (cluster < EXFAT_CLUSTER_FIRST ||
            cluster > fs->boot.cluster_count + 1U) return false;
        if (!no_fat && !exfat_fat_get(fs, cluster, &next)) return false;
        if (!exfat_bitmap_set(fs, cluster, false)) return false;
        if (!no_fat && !exfat_fat_set(fs, cluster, 0U)) return false;
        if (no_fat) {
            if (cluster == fs->boot.cluster_count + 1U) {
                ended = true;
                break;
            }
            cluster++;
        } else {
            if (next >= EXFAT_CLUSTER_EOC_MIN) {
                ended = true;
                break;
            }
            if (next < 2U || next > fs->boot.cluster_count + 1U) return false;
            cluster = next;
        }
    }
    return ended;
}

static bool exfat_append_directory_cluster(exfat_fs_t *fs, u32 first,
                                            u32 *out_cluster)
{
    u32 last = first;
    u32 next;
    u32 added = 0;
    bool ended = false;

    if (!fs || first < 2U || !out_cluster) return false;
    for (u64 steps = 0; steps < fs->boot.cluster_count; steps++) {
        if (!exfat_fat_get(fs, last, &next)) return false;
        if (next >= EXFAT_CLUSTER_EOC_MIN) {
            ended = true;
            break;
        }
        if (next < 2U || next > fs->boot.cluster_count + 1U) return false;
        last = next;
    }
    if (!ended) return false;
    if (!exfat_alloc_cluster(fs, &added) ||
        !exfat_fat_set(fs, last, added)) {
        if (added >= 2U) (void)exfat_free_chain(fs, added, false,
                                                fs->cluster_bytes);
        return false;
    }
    *out_cluster = added;
    return true;
}

static bool exfat_ensure_directory_capacity(exfat_fs_t *fs, u32 first,
                                            bool no_fat, u64 needed)
{
    u64 capacity;

    if (!exfat_directory_capacity(fs, first, no_fat, &capacity)) return false;
    while (capacity < needed) {
        u32 added;
        if (no_fat || !exfat_append_directory_cluster(fs, first, &added) ||
            !exfat_add_u64(capacity, fs->cluster_bytes, &capacity)) return false;
    }
    return true;
}

static bool exfat_find_free_entries(exfat_fs_t *fs, u32 first, bool no_fat,
                                    u32 count, u64 *out_offset)
{
    u64 capacity;
    u64 extra;
    u64 needed;
    u64 start;
    u64 entries_bytes;
    u32 run = 0;
    u64 run_start = 0;
    u8 entry[EXFAT_ENTRY_BYTES];

    if (!fs || !out_offset || !count ||
        !exfat_directory_capacity(fs, first, no_fat, &capacity) ||
        !exfat_mul_u64((u64)count, EXFAT_ENTRY_BYTES, &entries_bytes))
        return false;
    for (u64 offset = 0; offset + EXFAT_ENTRY_BYTES <= capacity;
         offset += EXFAT_ENTRY_BYTES) {
        if (!exfat_dir_byte_read(fs, first, no_fat, offset, entry,
                                 sizeof(entry))) return false;
        if (entry[0] == EXFAT_ENTRY_END || entry[0] == EXFAT_ENTRY_DELETED) {
            if (!run) run_start = offset;
            if (++run == count) {
                if (!exfat_add_u64(run_start, entries_bytes, &needed))
                    return false;
                if (needed == capacity) {
                    /* Keep an end marker after a set that exactly fills
                     * the current directory extent.  The newly allocated
                     * cluster is zeroed by exfat_alloc_cluster(), so its
                     * first entry supplies that marker. */
                    if (!exfat_add_u64(capacity, EXFAT_ENTRY_BYTES, &needed) ||
                        !exfat_ensure_directory_capacity(fs, first, no_fat,
                                                         needed)) return false;
                }
                *out_offset = run_start;
                return true;
            }
        } else run = 0;
    }
    extra = entries_bytes;
    if (!exfat_add_u64(run ? run_start : capacity, extra, &needed) ||
        !exfat_ensure_directory_capacity(fs, first, no_fat, needed))
        return false;
    /* The end marker is part of the free tail.  If a set does not fit in
     * that tail, start at its first free entry and let the set cross into
     * the newly appended cluster.  Starting at `capacity` would leave the
     * old end marker in place, causing standard exFAT readers to stop before
     * the new entry set. */
    start = run ? run_start : capacity;
    *out_offset = start;
    return true;
}

static bool exfat_directory_next(exfat_fs_t *fs, u32 first, bool no_fat,
                                 u64 *io_offset, exfat_entry_info_t *out)
{
    u64 maximum;
    u8 entry[EXFAT_ENTRY_BYTES];

    if (!fs || !io_offset || !out ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &maximum))
        return false;
    while (*io_offset + EXFAT_ENTRY_BYTES <= maximum) {
        u64 offset = *io_offset;
        u8 type;
        if (!exfat_dir_byte_read(fs, first, no_fat, offset, entry,
                                 sizeof(entry))) return false;
        type = entry[0];
        if (type == EXFAT_ENTRY_END) return false;
        if (type == EXFAT_ENTRY_FILE) {
            if (!exfat_entry_set_read(fs, first, no_fat, offset, out)) return false;
            *io_offset += (u64)out->entry_count * EXFAT_ENTRY_BYTES;
            if (out->attributes & EXFAT_ATTR_SYSTEM) continue;
            return true;
        }
        *io_offset += EXFAT_ENTRY_BYTES;
    }
    return false;
}

static bool exfat_find_entry(exfat_fs_t *fs, u32 first, bool no_fat,
                             const char *name, exfat_entry_info_t *out)
{
    u64 offset = 0;
    exfat_entry_info_t item;

    if (!fs || !name || !out) return false;
    while (exfat_directory_next(fs, first, no_fat, &offset, &item)) {
        u16 query[EXFAT_MAX_NAME_UNITS];
        u16 query_units;
        if (!exfat_utf8_to_utf16(name, query, &query_units, false)) return false;
        if (query_units != item.name_length) continue;
        bool same = true;
        for (u16 i = 0; i < query_units; i++) {
            if (exfat_upcase_unit(fs, query[i]) !=
                exfat_upcase_unit(fs, item.name_units[i])) {
                same = false;
                break;
            }
        }
        if (same) {
            *out = item;
            return true;
        }
    }
    return false;
}

static vfs_node_t *exfat_make_node(vfs_node_t *parent,
                                   const exfat_entry_info_t *entry)
{
    exfat_node_t *private_node;
    vfs_node_t *node;
    u32 permissions = EXFAT_VOLUME_PERMISSIONS;

    if (!parent || !entry) return NULL;
    private_node = (exfat_node_t *)kmalloc(sizeof(*private_node));
    node = (vfs_node_t *)kmalloc(sizeof(*node));
    if (!private_node || !node) {
        kfree(private_node);
        kfree(node);
        return NULL;
    }
    memset(private_node, 0, sizeof(*private_node));
    private_node->first_cluster = entry->first_cluster;
    private_node->no_fat_chain = (entry->stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) != 0U;
    private_node->attributes = entry->attributes;
    private_node->data_length = entry->data_length;
    private_node->valid_data_length = entry->valid_data_length;
    private_node->entry_offset = entry->entry_offset;
    private_node->parent_cluster = entry->parent_cluster;
    private_node->parent_no_fat_chain = entry->parent_no_fat_chain;
    private_node->entry_count = entry->entry_count;
    memset(node, 0, sizeof(*node));
    node->inode = ((u64)entry->parent_cluster << 32U) ^ entry->entry_offset;
    node->type = (entry->attributes & EXFAT_ATTR_DIRECTORY)
        ? VFS_TYPE_DIRECTORY : VFS_TYPE_FILE;
    node->size = entry->data_length;
    /* Preserve the portable exFAT read-only attribute as VFS write
     * protection.  Without this, an imported read-only file would appear
     * writable merely because the removable-volume policy is shared. */
    if (entry->attributes & EXFAT_ATTR_READ_ONLY)
        permissions &= ~(VFS_PERMISSION_OWNER_WRITE |
                         VFS_PERMISSION_OTHER_WRITE);
    vfs_node_set_security(node, VFS_UID_SYSTEM, permissions);
    node->ref_count = 1;
    node->super = parent->super;
    node->fs_data = private_node;
    node->ops = &exfat_node_ops;
    vfs_node_register(node);
    return node;
}

static bool exfat_node_entry_read(exfat_node_t *node, exfat_fs_t *fs,
                                  u8 *set, u32 capacity)
{
    u32 bytes;

    if (!node || !fs || !set || node->entry_count == 0U ||
        node->entry_count > EXFAT_MAX_SECONDARY + 1U) return false;
    bytes = (u32)node->entry_count * EXFAT_ENTRY_BYTES;
    if (bytes > capacity) return false;
    return exfat_dir_byte_read(fs, node->parent_cluster,
                               node->parent_no_fat_chain, node->entry_offset,
                               set, bytes);
}

static bool exfat_node_metadata_write(exfat_node_t *node, exfat_fs_t *fs)
{
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u32 bytes;

    if (!node || !fs || !exfat_node_entry_read(node, fs, set, sizeof(set)))
        return false;
    bytes = (u32)node->entry_count * EXFAT_ENTRY_BYTES;
    exfat_put16(set + 4U, node->attributes);
    exfat_put16(set + EXFAT_ENTRY_BYTES + 1U,
                node->no_fat_chain ? EXFAT_STREAM_NO_FAT_CHAIN : 0U);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 8U, node->valid_data_length);
    exfat_put32(set + EXFAT_ENTRY_BYTES + 20U, node->first_cluster);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 24U, node->data_length);
    exfat_put16(set + 2U, (u16)exfat_entry_checksum(set, node->entry_count));
    return exfat_dir_byte_write(fs, node->parent_cluster,
                                node->parent_no_fat_chain, node->entry_offset,
                                set, bytes);
}

static bool exfat_directory_length_refresh(exfat_fs_t *fs,
                                            exfat_node_t *directory,
                                            u64 previous_capacity)
{
    u64 capacity;
    u64 old_data;
    u64 old_valid;

    if (!fs || !directory ||
        !exfat_directory_capacity(fs, directory->first_cluster,
                                   directory->no_fat_chain, &capacity))
        return false;
    if (capacity <= previous_capacity) return true;
    old_data = directory->data_length;
    old_valid = directory->valid_data_length;
    directory->data_length = capacity;
    directory->valid_data_length = capacity;
    /* The root directory has no file entry set of its own. */
    if (!directory->entry_count) return true;
    if (exfat_node_metadata_write(directory, fs)) return true;
    directory->data_length = old_data;
    directory->valid_data_length = old_valid;
    return false;
}

static bool exfat_file_cluster(exfat_fs_t *fs, const exfat_node_t *node,
                               u64 index, u32 *out_cluster)
{
    if (!fs || !node || !node->first_cluster ||
        !exfat_chain_cluster(fs, node->first_cluster, node->no_fat_chain,
                             index, out_cluster)) return false;
    return true;
}

static bool exfat_file_read_bytes(exfat_fs_t *fs, const exfat_node_t *node,
                                  u64 offset, u64 length, void *buffer)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 *out = (u8 *)buffer;

    if (!fs || !node || !buffer || !length || offset > node->data_length ||
        length > node->data_length - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within = offset % fs->cluster_bytes;
        u64 sector_index = within / EXFAT_SECTOR_BYTES;
        u32 sector_offset = (u32)(within % EXFAT_SECTOR_BYTES);
        u32 cluster;
        u64 lba;
        usize amount = EXFAT_SECTOR_BYTES - sector_offset;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_file_cluster(fs, node, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(out, sector + sector_offset, amount);
        out += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

static bool exfat_file_write_bytes(exfat_fs_t *fs, const exfat_node_t *node,
                                   u64 offset, u64 length, const void *buffer)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    const u8 *input = (const u8 *)buffer;

    if (!fs || !node || !buffer || !length || offset > node->data_length ||
        length > node->data_length - offset) return false;
    while (length) {
        u64 cluster_index = offset / fs->cluster_bytes;
        u64 within = offset % fs->cluster_bytes;
        u64 sector_index = within / EXFAT_SECTOR_BYTES;
        u32 sector_offset = (u32)(within % EXFAT_SECTOR_BYTES);
        u32 cluster;
        u64 lba;
        usize amount = EXFAT_SECTOR_BYTES - sector_offset;
        if ((u64)amount > length) amount = (usize)length;
        if (!exfat_file_cluster(fs, node, cluster_index, &cluster) ||
            (lba = exfat_cluster_lba(fs, cluster)) == ~(u64)0 ||
            !exfat_add_u64(lba, sector_index, &lba) ||
            !exfat_read(fs, lba, 1U, sector)) return false;
        memcpy(sector + sector_offset, input, amount);
        if (!exfat_write(fs, lba, 1U, sector)) return false;
        input += amount;
        offset += amount;
        length -= amount;
    }
    return true;
}

static bool exfat_file_zero_bytes(exfat_fs_t *fs, const exfat_node_t *node,
                                  u64 offset, u64 length)
{
    u8 zero[EXFAT_SECTOR_BYTES];

    if (!fs || !node || !length || offset > node->data_length ||
        length > node->data_length - offset) return false;
    memset(zero, 0, sizeof(zero));
    while (length) {
        u64 amount = length < sizeof(zero) ? length : sizeof(zero);
        if (!exfat_file_write_bytes(fs, node, offset, amount, zero))
            return false;
        offset += amount;
        length -= amount;
    }
    return true;
}

static bool exfat_allocate_file_space(exfat_fs_t *fs, exfat_node_t *node,
                                      u64 required_clusters)
{
    u64 old_clusters = 0;
    u32 last = 0;
    bool ended = false;

    if (!fs || !node || required_clusters > fs->boot.cluster_count) return false;
    if (node->first_cluster) {
        if (node->no_fat_chain) {
            old_clusters = (node->data_length + fs->cluster_bytes - 1ULL) /
                           fs->cluster_bytes;
            if (!old_clusters) old_clusters = 1U;
            if (old_clusters > fs->boot.cluster_count + 1U -
                               node->first_cluster) return false;
            last = node->first_cluster + (u32)old_clusters - 1U;
        } else {
            u32 cluster = node->first_cluster;
            for (u64 step = 0; step < fs->boot.cluster_count; step++) {
                u32 next;
                old_clusters++;
                last = cluster;
                if (!exfat_fat_get(fs, cluster, &next)) return false;
                if (next >= EXFAT_CLUSTER_EOC_MIN) {
                    ended = true;
                    break;
                }
                if (next < 2U || next > fs->boot.cluster_count + 1U)
                    return false;
                cluster = next;
            }
            if (!ended) return false;
        }
    }
    if (old_clusters >= required_clusters) return true;
    if (node->no_fat_chain && old_clusters) {
        u64 added_count = required_clusters - old_clusters;
        u32 added_first;

        /* Keep a stream contiguous when the adjacent extent is still free.
         * A high-offset write commonly grows a freshly allocated file by one
         * cluster.  Converting every existing cluster to a FAT chain in that
         * case is both unnecessary and can leave a large allocation behind
         * if removal interrupts the conversion. */
        if (old_clusters <= fs->boot.cluster_count + 1ULL -
                            node->first_cluster) {
            added_first = node->first_cluster + (u32)old_clusters;
            if (added_count <= fs->boot.cluster_count + 1ULL - added_first &&
                exfat_bitmap_range_unused(fs, added_first, added_count) &&
                exfat_bitmap_set_range(fs, added_first, added_count, true)) {
                if (exfat_zero_cluster_run(fs, added_first, added_count))
                    return true;
                (void)exfat_bitmap_set_range(fs, added_first, added_count,
                                             false);
                return false;
            }
        }
        u32 cluster = node->first_cluster;
        for (u64 index = 0; index < old_clusters; index++) {
            u32 next = index + 1U < old_clusters ? cluster + 1U
                                                 : EXFAT_CLUSTER_EOC;
            if (!exfat_fat_set(fs, cluster, next)) return false;
            cluster++;
        }
        node->no_fat_chain = false;
    }
    if (!old_clusters) {
        /* A freshly created file can use the standard contiguous stream
         * representation.  Besides avoiding needless FAT traffic, this
         * keeps large valid-data writes bounded by the actual data transfer
         * rather than one bitmap/FAT read-modify-write per cluster. */
        if (exfat_allocate_contiguous_run(fs, required_clusters, &last)) {
            node->first_cluster = last;
            node->no_fat_chain = true;
            return true;
        }
        if (!exfat_alloc_cluster(fs, &last)) return false;
        node->first_cluster = last;
        node->no_fat_chain = false;
        old_clusters = 1U;
    }
    while (old_clusters < required_clusters) {
        u32 added = 0;
        if (!exfat_alloc_cluster(fs, &added))
            return false;
        if (!exfat_fat_set(fs, last, added)) {
            (void)exfat_free_chain(fs, added, false, fs->cluster_bytes);
            return false;
        }
        last = added;
        old_clusters++;
    }
    return true;
}

static u64 exfat_node_read(vfs_node_t *node, u64 offset, u64 size,
                           void *buffer)
{
    exfat_fs_t *fs;
    exfat_node_t *private_node;
    u64 available;
    u64 valid;

    if (!node || !node->super || !node->super->private_data ||
        node->type != VFS_TYPE_FILE || (size && !buffer)) return 0;
    fs = (exfat_fs_t *)node->super->private_data;
    private_node = (exfat_node_t *)node->fs_data;
    if (!private_node || offset >= private_node->data_length || !size) return 0;
    available = private_node->data_length - offset;
    if (size > available) size = available;
    valid = private_node->valid_data_length > offset
        ? private_node->valid_data_length - offset : 0ULL;
    if (valid > size) valid = size;
    if (valid && !exfat_file_read_bytes(fs, private_node, offset, valid,
                                        buffer)) return 0;
    if (valid < size) {
        memset((u8 *)buffer + valid, 0, (usize)(size - valid));
        if (private_node->data_length > private_node->valid_data_length &&
            valid < size && private_node->valid_data_length > offset) {
            /* The region after ValidDataLength is intentionally zero-filled
             * for the caller; it need not have been read from media. */
        }
    }
    return size;
}

static u64 exfat_node_write(vfs_node_t *node, u64 offset, u64 size,
                            const void *buffer)
{
    exfat_fs_t *fs;
    exfat_node_t *private_node;
    u64 old_valid;
    u64 old_data;
    u64 final_size;
    u64 required;

    if (!node || !node->super || !node->super->private_data ||
        node->type != VFS_TYPE_FILE || (size && !buffer) || !size) return 0;
    private_node = (exfat_node_t *)node->fs_data;
    fs = (exfat_fs_t *)node->super->private_data;
    if (!private_node || fs->read_only ||
        (private_node->attributes & EXFAT_ATTR_READ_ONLY) != 0U ||
        offset > ~(u64)0 - size) return 0;
    final_size = offset + size;
    if (final_size > ~(u64)0 - (fs->cluster_bytes - 1ULL)) return 0;
    required = final_size / fs->cluster_bytes;
    if (final_size % fs->cluster_bytes) required++;
    old_valid = private_node->valid_data_length;
    old_data = private_node->data_length;
    if (!exfat_set_volume_dirty(fs, true)) return 0;
    if (!exfat_allocate_file_space(fs, private_node, required)) return 0;
    /* An in-place write must never shorten the stream.  In particular, a
     * write below EOF may be followed by a write above 4 GiB; recording the
     * first write's end as DataLength while retaining the old ValidDataLength
     * produces an invalid on-disk entry set (VDL > DataLength). */
    if (final_size > private_node->data_length)
        private_node->data_length = final_size;
    /* New allocations were explicitly zeroed before they became reachable.
     * Only the already allocated tail between ValidDataLength and the old
     * DataLength can contain bytes that must be materialized before VDL is
     * advanced across it.  Re-zeroing every newly allocated byte turns a
     * legitimate large seek/write into duplicate whole-volume I/O. */
    if (old_valid < offset && old_valid < old_data) {
        u64 zero_end = offset < old_data ? offset : old_data;
        if (zero_end > old_valid &&
            !exfat_file_zero_bytes(fs, private_node, old_valid,
                                   zero_end - old_valid)) return 0;
    }
    if (!exfat_file_write_bytes(fs, private_node, offset, size, buffer)) return 0;
    if (offset > old_valid) {
        private_node->valid_data_length = offset + size;
    } else if (final_size > private_node->valid_data_length) {
        private_node->valid_data_length = final_size;
    }
    if (!exfat_node_metadata_write(private_node, fs)) return 0;
    node->size = private_node->data_length;
    return size;
}

static bool exfat_build_file_set(const exfat_fs_t *fs, const char *name,
                                 u16 attributes, u32 first_cluster,
                                 u64 valid_length, u64 data_length,
                                 bool no_fat_chain,
                                 u8 *set, u8 *out_count)
{
    u16 units[EXFAT_MAX_NAME_UNITS];
    u16 unit_count;
    u32 name_entries;
    u32 total_entries;

    if (!fs || !name || !set || !out_count ||
        !exfat_utf8_to_utf16(name, units, &unit_count, false)) return false;
    name_entries = (unit_count + 14U) / 15U;
    total_entries = 2U + name_entries;
    if (!unit_count || name_entries == 0U ||
        total_entries > EXFAT_MAX_SECONDARY + 1U) return false;
    memset(set, 0, (usize)total_entries * EXFAT_ENTRY_BYTES);
    set[0] = EXFAT_ENTRY_FILE;
    set[1] = (u8)(total_entries - 1U);
    exfat_put16(set + 4U, attributes);
    set[EXFAT_ENTRY_BYTES] = EXFAT_ENTRY_STREAM;
    exfat_put16(set + EXFAT_ENTRY_BYTES + 1U,
                no_fat_chain ? EXFAT_STREAM_NO_FAT_CHAIN : 0U);
    set[EXFAT_ENTRY_BYTES + 3U] = (u8)unit_count;
    exfat_put16(set + EXFAT_ENTRY_BYTES + 4U,
                exfat_name_hash(fs, units, unit_count));
    exfat_put64(set + EXFAT_ENTRY_BYTES + 8U, valid_length);
    exfat_put32(set + EXFAT_ENTRY_BYTES + 20U, first_cluster);
    exfat_put64(set + EXFAT_ENTRY_BYTES + 24U, data_length);
    for (u32 entry = 0; entry < name_entries; entry++) {
        u8 *name_entry = set + (2U + entry) * EXFAT_ENTRY_BYTES;
        name_entry[0] = EXFAT_ENTRY_NAME;
        for (u32 index = 0; index < 15U; index++) {
            u32 unit = entry * 15U + index;
            exfat_put16(name_entry + 2U + index * 2U,
                        unit < unit_count ? units[unit] : 0U);
        }
    }
    exfat_put16(set + 2U,
                (u16)exfat_entry_checksum(set, total_entries));
    *out_count = (u8)total_entries;
    return true;
}

static bool exfat_write_entry_set(exfat_fs_t *fs, u32 parent_cluster,
                                  bool parent_no_fat, u64 offset,
                                  const u8 *set, u8 entry_count)
{
    u64 needed;

    if (!fs || !set || !entry_count ||
        !exfat_add_u64(offset, (u64)entry_count * EXFAT_ENTRY_BYTES,
                       &needed) ||
        !exfat_ensure_directory_capacity(fs, parent_cluster, parent_no_fat,
                                         needed) ||
        !exfat_dir_byte_write(fs, parent_cluster, parent_no_fat, offset, set,
                              (usize)entry_count * EXFAT_ENTRY_BYTES)) return false;
    /* Do not write an end marker after a reused deleted run.  A live entry
     * set may follow that run; its existing end marker must be preserved. */
    return true;
}

static bool exfat_mark_entry_deleted(exfat_fs_t *fs,
                                     const exfat_entry_info_t *entry)
{
    u8 deleted = EXFAT_ENTRY_DELETED;
    if (!fs || !entry || !entry->entry_count) return false;
    for (u32 index = 0; index < entry->entry_count; index++) {
        if (!exfat_dir_byte_write(fs, entry->parent_cluster,
                                  entry->parent_no_fat_chain,
                                  entry->entry_offset +
                                  (u64)index * EXFAT_ENTRY_BYTES,
                                  &deleted, 1U)) return false;
    }
    return true;
}

static vfs_node_t *exfat_finddir(vfs_node_t *dir, const char *name)
{
    exfat_fs_t *fs;
    exfat_node_t *private_dir;
    exfat_entry_info_t entry;

    if (!dir || !name || dir->type != VFS_TYPE_DIRECTORY || !dir->super ||
        !dir->super->private_data || !dir->fs_data) return NULL;
    fs = (exfat_fs_t *)dir->super->private_data;
    private_dir = (exfat_node_t *)dir->fs_data;
    if (!exfat_find_entry(fs, private_dir->first_cluster,
                          private_dir->no_fat_chain, name, &entry)) return NULL;
    return exfat_make_node(dir, &entry);
}

static bool exfat_readdir(vfs_node_t *dir, u32 index, vfs_dirent_t *out_entry)
{
    exfat_fs_t *fs;
    exfat_node_t *private_dir;
    exfat_entry_info_t entry;
    u64 offset = 0;

    if (!dir || !out_entry || dir->type != VFS_TYPE_DIRECTORY ||
        !dir->super || !dir->super->private_data || !dir->fs_data) return false;
    fs = (exfat_fs_t *)dir->super->private_data;
    private_dir = (exfat_node_t *)dir->fs_data;
    for (u32 visible = 0; visible <= index; visible++) {
        if (!exfat_directory_next(fs, private_dir->first_cluster,
                                  private_dir->no_fat_chain, &offset, &entry))
            return false;
        if (visible == index) {
            strcpy(out_entry->name, entry.name);
            out_entry->inode = ((u64)entry.parent_cluster << 32U) ^
                               entry.entry_offset;
            out_entry->type = (entry.attributes & EXFAT_ATTR_DIRECTORY)
                ? VFS_TYPE_DIRECTORY : VFS_TYPE_FILE;
            return true;
        }
    }
    return false;
}

static bool exfat_readdir_open(vfs_node_t *dir, void **out_state)
{
    exfat_node_t *private_dir;
    exfat_directory_cursor_t *cursor;

    if (!dir || !out_state || dir->type != VFS_TYPE_DIRECTORY ||
        !dir->super || !dir->fs_data) return false;
    private_dir = (exfat_node_t *)dir->fs_data;
    cursor = (exfat_directory_cursor_t *)kmalloc(sizeof(*cursor));
    if (!cursor) return false;
    cursor->fs = (exfat_fs_t *)dir->super->private_data;
    cursor->first_cluster = private_dir->first_cluster;
    cursor->no_fat_chain = private_dir->no_fat_chain;
    cursor->offset = 0;
    cursor->ended = false;
    *out_state = cursor;
    return true;
}

static bool exfat_readdir_next(void *state, vfs_dirent_t *out_entry)
{
    exfat_directory_cursor_t *cursor = (exfat_directory_cursor_t *)state;
    exfat_entry_info_t entry;

    if (!cursor || !out_entry || cursor->ended) return false;
    if (!exfat_directory_next(cursor->fs, cursor->first_cluster,
                              cursor->no_fat_chain, &cursor->offset, &entry)) {
        cursor->ended = true;
        return false;
    }
    strcpy(out_entry->name, entry.name);
    out_entry->inode = ((u64)entry.parent_cluster << 32U) ^ entry.entry_offset;
    out_entry->type = (entry.attributes & EXFAT_ATTR_DIRECTORY)
        ? VFS_TYPE_DIRECTORY : VFS_TYPE_FILE;
    return true;
}

static void exfat_readdir_close(void *state)
{
    kfree(state);
}

static int exfat_create_internal(vfs_node_t *dir, const char *name,
                                 u16 attributes, u32 owner_uid,
                                 u32 permissions, vfs_node_t **out_node)
{
    exfat_fs_t *fs;
    exfat_node_t *private_dir;
    exfat_entry_info_t existing;
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u8 count;
    u64 offset;
    u64 previous_capacity;
    u32 first_cluster = 0;

    if (!dir || !name || !out_node || dir->type != VFS_TYPE_DIRECTORY ||
        !dir->super || !dir->super->private_data || !dir->fs_data ||
        !*name) return VFS_ERR_INVALID_PARAM;
    fs = (exfat_fs_t *)dir->super->private_data;
    private_dir = (exfat_node_t *)dir->fs_data;
    if (exfat_find_entry(fs, private_dir->first_cluster,
                         private_dir->no_fat_chain, name, &existing))
        return VFS_ERR_INVALID_PARAM;
    if (!exfat_build_file_set(fs, name, attributes, 0U, 0U, 0U, false,
                              set, &count))
        return VFS_ERR_INVALID_PARAM;
    if (!exfat_set_volume_dirty(fs, true)) return VFS_ERR_IO;
    if (attributes & EXFAT_ATTR_DIRECTORY) {
        if (!exfat_alloc_cluster(fs, &first_cluster)) return VFS_ERR_NO_SPACE;
        memset(set, 0, sizeof(set));
        if (!exfat_build_file_set(fs, name, attributes, first_cluster,
                                  fs->cluster_bytes, fs->cluster_bytes, false,
                                  set, &count)) {
            (void)exfat_free_chain(fs, first_cluster, false, fs->cluster_bytes);
            return VFS_ERR_INVALID_PARAM;
        }
    }
    if (!exfat_directory_capacity(fs, private_dir->first_cluster,
                                  private_dir->no_fat_chain,
                                  &previous_capacity))
        return VFS_ERR_IO;
    if (!exfat_find_free_entries(fs, private_dir->first_cluster,
                                 private_dir->no_fat_chain, count, &offset) ||
        !exfat_write_entry_set(fs, private_dir->first_cluster,
                               private_dir->no_fat_chain, offset, set, count)) {
        if (first_cluster) (void)exfat_free_chain(fs, first_cluster, false,
                                                  fs->cluster_bytes);
        return VFS_ERR_IO;
    }
    if (!exfat_directory_length_refresh(fs, private_dir, previous_capacity))
        return VFS_ERR_IO;
    *out_node = exfat_make_node(dir, &(exfat_entry_info_t){
        offset, private_dir->first_cluster, private_dir->no_fat_chain, count,
        attributes, first_cluster, 0U,
        (attributes & EXFAT_ATTR_DIRECTORY) ? fs->cluster_bytes : 0U,
        (attributes & EXFAT_ATTR_DIRECTORY) ? fs->cluster_bytes : 0U,
        {0}, 0U, {0}});
    if (!*out_node) return VFS_ERR_NO_MEM;
    vfs_node_set_security(*out_node, owner_uid, permissions);
    return VFS_OK;
}

static int exfat_create(vfs_node_t *dir, const char *name,
                        vfs_node_t **out_node)
{
    u32 owner;
    if (!vfs_current_uid(&owner)) return VFS_ERR_ACCESS_DENIED;
    return exfat_create_internal(dir, name, 0U, owner,
                                 VFS_DEFAULT_FILE_PERMISSIONS,
                                 out_node);
}

static int exfat_mkdir(vfs_node_t *dir, const char *name,
                       vfs_node_t **out_node)
{
    u32 owner;
    if (!vfs_current_uid(&owner)) return VFS_ERR_ACCESS_DENIED;
    return exfat_create_internal(dir, name, EXFAT_ATTR_DIRECTORY, owner,
                                 VFS_DEFAULT_DIRECTORY_PERMISSIONS,
                                 out_node);
}

static int exfat_create_owned(vfs_node_t *dir, const char *name, u32 owner,
                              u32 permissions, vfs_node_t **out_node)
{
    if ((permissions & ~VFS_PERMISSION_KNOWN) || !permissions)
        return VFS_ERR_INVALID_PARAM;
    return exfat_create_internal(dir, name, 0U, owner, permissions, out_node);
}

static int exfat_mkdir_owned(vfs_node_t *dir, const char *name, u32 owner,
                             u32 permissions, vfs_node_t **out_node)
{
    if ((permissions & ~VFS_PERMISSION_KNOWN) || !permissions)
        return VFS_ERR_INVALID_PARAM;
    return exfat_create_internal(dir, name, EXFAT_ATTR_DIRECTORY, owner,
                                 permissions, out_node);
}

static bool exfat_directory_empty(exfat_fs_t *fs, const exfat_entry_info_t *dir)
{
    u64 offset = 0;
    u64 maximum;
    bool no_fat;
    u8 entry[EXFAT_ENTRY_BYTES];
    exfat_entry_info_t child;

    if (!fs || !dir || !(dir->attributes & EXFAT_ATTR_DIRECTORY) ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &maximum))
        return false;
    no_fat = (dir->stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) != 0U;
    while (offset + EXFAT_ENTRY_BYTES <= maximum) {
        u8 type;
        if (!exfat_dir_byte_read(fs, dir->first_cluster, no_fat, offset,
                                 entry, sizeof(entry))) return false;
        type = entry[0];
        if (type == EXFAT_ENTRY_END) return true;
        if (type == EXFAT_ENTRY_FILE) {
            if (!exfat_entry_set_read(fs, dir->first_cluster, no_fat, offset,
                                      &child)) return false;
            return false;
        }
        offset += EXFAT_ENTRY_BYTES;
    }
    return false;
}

static int exfat_delete(vfs_node_t *parent, const char *name,
                        bool directory_only)
{
    exfat_fs_t *fs;
    exfat_node_t *private_parent;
    exfat_entry_info_t entry;

    if (!parent || !name || parent->type != VFS_TYPE_DIRECTORY ||
        !parent->super || !parent->super->private_data || !parent->fs_data)
        return VFS_ERR_INVALID_PARAM;
    fs = (exfat_fs_t *)parent->super->private_data;
    private_parent = (exfat_node_t *)parent->fs_data;
    if (!exfat_find_entry(fs, private_parent->first_cluster,
                          private_parent->no_fat_chain, name, &entry))
        return VFS_ERR_NOT_FOUND;
    if (directory_only && !(entry.attributes & EXFAT_ATTR_DIRECTORY))
        return VFS_ERR_INVALID_PARAM;
    if (!directory_only && (entry.attributes & EXFAT_ATTR_DIRECTORY))
        return VFS_ERR_INVALID_PARAM;
    if (directory_only && !exfat_directory_empty(fs, &entry))
        return VFS_ERR_NOT_EMPTY;
    if (!exfat_set_volume_dirty(fs, true)) return VFS_ERR_IO;
    if (!exfat_mark_entry_deleted(fs, &entry)) return VFS_ERR_IO;
    if (entry.first_cluster &&
        !exfat_free_chain(fs, entry.first_cluster,
                          (entry.stream_flags & EXFAT_STREAM_NO_FAT_CHAIN) != 0U,
                          entry.data_length)) return VFS_ERR_IO;
    return VFS_OK;
}

static int exfat_unlink(vfs_node_t *parent, const char *name)
{
    return exfat_delete(parent, name, false);
}

static int exfat_rmdir(vfs_node_t *parent, const char *name)
{
    if (!name || !strcmp(name, "/") || !strcmp(name, ""))
        return VFS_ERR_INVALID_PARAM;
    return exfat_delete(parent, name, true);
}

static int exfat_rename(vfs_node_t *src_dir, const char *src_name,
                        vfs_node_t *dst_dir, const char *dst_name)
{
    exfat_fs_t *fs;
    exfat_node_t *src_parent;
    exfat_node_t *dst_parent;
    exfat_entry_info_t source;
    exfat_entry_info_t destination;
    bool destination_exists;
    u16 units[EXFAT_MAX_NAME_UNITS];
    u16 unit_count;
    u8 set[(EXFAT_MAX_SECONDARY + 1U) * EXFAT_ENTRY_BYTES];
    u8 count;
    u64 offset;
    u64 previous_capacity;

    if (!src_dir || !dst_dir || !src_name || !dst_name ||
        src_dir->type != VFS_TYPE_DIRECTORY || dst_dir->type != VFS_TYPE_DIRECTORY ||
        src_dir->super != dst_dir->super || !src_dir->fs_data ||
        !dst_dir->fs_data) return VFS_ERR_INVALID_PARAM;
    fs = (exfat_fs_t *)src_dir->super->private_data;
    src_parent = (exfat_node_t *)src_dir->fs_data;
    dst_parent = (exfat_node_t *)dst_dir->fs_data;
    if (!exfat_find_entry(fs, src_parent->first_cluster,
                          src_parent->no_fat_chain, src_name, &source))
        return VFS_ERR_NOT_FOUND;
    destination_exists = exfat_find_entry(fs, dst_parent->first_cluster,
                                          dst_parent->no_fat_chain, dst_name,
                                          &destination);
    if (destination_exists) {
        if (destination.entry_offset != source.entry_offset ||
            destination.parent_cluster != source.parent_cluster)
            return VFS_ERR_INVALID_PARAM;
        /* A case-only rename updates the existing entry set in place. */
    }
    if (!exfat_utf8_to_utf16(dst_name, units, &unit_count, false))
        return VFS_ERR_INVALID_PARAM;
    if (unit_count == 0U) return VFS_ERR_INVALID_PARAM;
    if (!exfat_build_file_set(fs, dst_name, source.attributes,
                              source.first_cluster, source.valid_data_length,
                              source.data_length,
                              (source.stream_flags &
                               EXFAT_STREAM_NO_FAT_CHAIN) != 0U,
                              set, &count))
        return VFS_ERR_INVALID_PARAM;
    if (!exfat_set_volume_dirty(fs, true)) return VFS_ERR_IO;
    if (destination_exists &&
        destination.entry_offset == source.entry_offset &&
        destination.parent_cluster == source.parent_cluster) {
        if (!exfat_dir_byte_write(fs, source.parent_cluster,
                                  source.parent_no_fat_chain,
                                  source.entry_offset, set,
                                  (usize)count * EXFAT_ENTRY_BYTES))
            return VFS_ERR_IO;
        return VFS_OK;
    }
    if (!exfat_directory_capacity(fs, dst_parent->first_cluster,
                                  dst_parent->no_fat_chain,
                                  &previous_capacity))
        return VFS_ERR_IO;
    if (!exfat_find_free_entries(fs, dst_parent->first_cluster,
                                 dst_parent->no_fat_chain, count, &offset) ||
        !exfat_write_entry_set(fs, dst_parent->first_cluster,
                               dst_parent->no_fat_chain, offset, set, count) ||
        !exfat_mark_entry_deleted(fs, &source)) return VFS_ERR_IO;
    if (!exfat_directory_length_refresh(fs, dst_parent, previous_capacity))
        return VFS_ERR_IO;
    return VFS_OK;
}

static int exfat_truncate(vfs_node_t *node)
{
    exfat_fs_t *fs;
    exfat_node_t *private_node;
    u32 first;
    bool no_fat;
    u64 length;

    if (!node || node->type != VFS_TYPE_FILE || !node->fs_data ||
        !node->super || !node->super->private_data) return VFS_ERR_INVALID_PARAM;
    fs = (exfat_fs_t *)node->super->private_data;
    private_node = (exfat_node_t *)node->fs_data;
    if (private_node->attributes & EXFAT_ATTR_READ_ONLY)
        return VFS_ERR_ACCESS_DENIED;
    first = private_node->first_cluster;
    no_fat = private_node->no_fat_chain;
    length = private_node->data_length;
    if (!exfat_set_volume_dirty(fs, true)) return VFS_ERR_IO;
    private_node->first_cluster = 0;
    private_node->no_fat_chain = false;
    private_node->data_length = 0;
    private_node->valid_data_length = 0;
    if (!exfat_node_metadata_write(private_node, fs)) {
        private_node->first_cluster = first;
        private_node->no_fat_chain = no_fat;
        private_node->data_length = length;
        private_node->valid_data_length = length;
        return VFS_ERR_IO;
    }
    if (first && !exfat_free_chain(fs, first, no_fat, length))
        return VFS_ERR_IO;
    node->size = 0;
    return VFS_OK;
}

