static int exfat_unmount(vfs_super_t *sb)
{
    exfat_fs_t *fs;
    if (!sb) return VFS_ERR_INVALID_PARAM;
    fs = (exfat_fs_t *)sb->private_data;
    exfat_free_state(fs);
    sb->private_data = NULL;
    return VFS_OK;
}

static int exfat_sync(vfs_super_t *sb)
{
    exfat_fs_t *fs;

    if (!sb || !sb->dev || !block_device_is_live(sb->dev))
        return VFS_ERR_DEVICE_GONE;
    fs = (exfat_fs_t *)sb->private_data;
    if (!fs || !block_flush(sb->dev)) return VFS_ERR_IO;
    if (fs->read_only) return VFS_OK;
    if (!exfat_set_volume_dirty(fs, false) || !block_flush(sb->dev))
        return VFS_ERR_IO;
    return VFS_OK;
}

static bool exfat_find_label(exfat_fs_t *fs, u64 *out_offset)
{
    u64 maximum;
    u8 entry[EXFAT_ENTRY_BYTES];

    if (!fs || !out_offset ||
        !exfat_mul_u64(fs->boot.cluster_count, fs->cluster_bytes, &maximum))
        return false;
    for (u64 offset = 0; offset + EXFAT_ENTRY_BYTES <= maximum;
         offset += EXFAT_ENTRY_BYTES) {
        if (!exfat_dir_byte_read(fs, fs->root_cluster, false, offset,
                                 entry, sizeof(entry))) return false;
        if (entry[0] == EXFAT_ENTRY_END) return false;
        if (entry[0] == EXFAT_ENTRY_LABEL) {
            *out_offset = offset;
            return true;
        }
        if (entry[0] == EXFAT_ENTRY_FILE) {
            u8 secondary = entry[1];
            if (secondary > EXFAT_MAX_SECONDARY) return false;
            offset += (u64)secondary * EXFAT_ENTRY_BYTES;
        }
    }
    return false;
}

bool exfat_set_label(block_device_t *dev, const char *label)
{
    exfat_fs_t *fs;
    u16 units[EXFAT_MAX_NAME_UNITS];
    u16 unit_count;
    u64 offset;
    u8 entry[EXFAT_ENTRY_BYTES];
    bool existing;
    bool was_dirty;

    if (!dev || !label || !exfat_utf8_to_utf16(label, units, &unit_count, true))
        return false;
    fs = exfat_new_state(dev);
    if (!fs) return false;
    was_dirty = (fs->boot.volume_flags & 0x0002U) != 0U;
    existing = exfat_find_label(fs, &offset);
    if (!existing) {
        if (!unit_count) {
            exfat_free_state(fs);
            return true;
        }
        if (!exfat_find_free_entries(fs, fs->root_cluster, false, 1U,
                                     &offset)) {
            exfat_free_state(fs);
            return false;
        }
    }
    if (!exfat_set_volume_dirty(fs, true)) {
        exfat_free_state(fs);
        return false;
    }
    if (!unit_count) {
        u8 deleted = EXFAT_ENTRY_DELETED;
        if (!exfat_dir_byte_write(fs, fs->root_cluster, false, offset,
                                  &deleted, 1U)) {
            exfat_free_state(fs);
            return false;
        }
    } else {
        memset(entry, 0, sizeof(entry));
        entry[0] = EXFAT_ENTRY_LABEL;
        entry[1] = (u8)unit_count;
        for (u16 i = 0; i < unit_count; i++)
            exfat_put16(entry + 2U + (u32)i * 2U, units[i]);
        if (!exfat_dir_byte_write(fs, fs->root_cluster, false, offset,
                                  entry, sizeof(entry))) {
            exfat_free_state(fs);
            return false;
        }
    }
    if (!block_flush(dev)) {
        exfat_free_state(fs);
        return false;
    }
    if ((!was_dirty && !exfat_set_volume_dirty(fs, false)) ||
        !block_flush(dev)) {
        exfat_free_state(fs);
        return false;
    }
    exfat_free_state(fs);
    return true;
}

static bool exfat_format_zero(block_device_t *dev, u64 lba, u64 sectors)
{
    /* Keep formatter traffic at the USB BOT backend's bounded 4 KiB request
     * size.  Zeroing an exFAT FAT one 512-byte sector at a time turns a
     * normal removable-media format into many thousands of command phases;
     * batching is materially faster without broadening the target extent. */
    u8 zero[EXFAT_SECTOR_BYTES * 8U];
    memset(zero, 0, sizeof(zero));
    while (sectors) {
        u32 batch = sectors > 8ULL ? 8U : (u32)sectors;

        if (lba > dev->sector_count || (u64)batch > dev->sector_count - lba ||
            !block_write(dev, lba, batch, zero))
            return false;
        lba += batch;
        sectors -= batch;
    }
    return true;
}

static bool exfat_format_fat_entry(block_device_t *dev, u32 fat_offset,
                                   u32 fat_length, u32 fat_count,
                                   u32 cluster, u32 value)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 byte_offset = (u64)cluster * 4ULL;
    u64 lba = fat_offset + byte_offset / EXFAT_SECTOR_BYTES;
    u32 within = (u32)(byte_offset % EXFAT_SECTOR_BYTES);

    if (within > EXFAT_SECTOR_BYTES - 4U ||
        !block_read(dev, lba, 1U, sector)) return false;
    exfat_put32(sector + within, value);
    for (u32 fat = 0; fat < fat_count; fat++)
        if (!block_write(dev, (u64)fat_offset + fat * fat_length +
                         byte_offset / EXFAT_SECTOR_BYTES, 1U, sector))
            return false;
    return true;
}

static bool exfat_format_bitmap_bit(block_device_t *dev, u64 bitmap_lba,
                                    u32 cluster, bool used)
{
    u8 sector[EXFAT_SECTOR_BYTES];
    u64 bit = (u64)cluster - 2ULL;
    u64 lba = bitmap_lba + bit / (EXFAT_SECTOR_BYTES * 8ULL);
    u32 at = (u32)((bit / 8ULL) % EXFAT_SECTOR_BYTES);

    if (!block_read(dev, lba, 1U, sector)) return false;
    if (used) sector[at] |= (u8)(1U << (bit % 8ULL));
    else sector[at] &= (u8)~(1U << (bit % 8ULL));
    return block_write(dev, lba, 1U, sector);
}

static u32 exfat_format_serial(block_device_t *dev)
{
    u64 value;
    if (entropy_random_u64(&value)) return (u32)(value ^ (value >> 32U));
    value = timekeeping_boot_id() ^ timekeeping_monotonic_ms() ^ dev->id;
    return (u32)(value ^ (value >> 32U));
}

bool exfat_format_device(block_device_t *dev)
{
    exfat_fs_t fs;
    exfat_boot_info_t boot;
    u8 *boot_region;
    u8 sector[EXFAT_SECTOR_BYTES];
    u8 *upcase_buffer;
    u64 heap_offset;
    u64 cluster_count;
    u64 fat_length;
    u64 bitmap_bytes;
    u64 bitmap_clusters;
    u64 upcase_clusters;
    u64 root_cluster;
    u64 metadata_last;
    u64 percent;
    u32 cluster_shift = 3U;
    bool geometry_found = false;

    if (!dev || dev->sector_size != EXFAT_SECTOR_BYTES ||
        !block_device_is_live(dev) || dev->sector_count < 4096ULL)
        return false;
    memset(&fs, 0, sizeof(fs));
    fs.dev = dev;
    fs.sector_size = EXFAT_SECTOR_BYTES;
    /* Keep the FAT and heap away from the two boot regions and align the
     * heap to 1 MiB, as common exFAT formatters do. */
    for (;;) {
        u64 sectors_per_cluster = 1ULL << cluster_shift;
        cluster_count = 0;
        heap_offset = 2048ULL;
        fat_length = 1ULL;
        for (u32 iteration = 0; iteration < 8U; iteration++) {
            u64 candidate;
            u64 aligned;
            u64 count_numerator;
            if (!exfat_add_u64(2048ULL, fat_length, &candidate) ||
                !exfat_add_u64(candidate, 2047ULL, &aligned)) break;
            candidate = aligned & ~2047ULL;
            heap_offset = candidate;
            if (heap_offset >= dev->sector_count) break;
            cluster_count = (dev->sector_count - heap_offset) /
                            sectors_per_cluster;
            if (!exfat_add_u64(cluster_count, 129ULL, &count_numerator)) {
                cluster_count = 0;
                break;
            }
            fat_length = count_numerator / 128ULL;
        }
        {
            u64 fat_end;
            if (heap_offset < dev->sector_count && cluster_count >= 2ULL &&
                fat_length <= 0xffffffffULL &&
                exfat_add_u64(heap_offset, fat_length, &fat_end) &&
                fat_end <= dev->sector_count) {
                geometry_found = true;
                break;
            }
        }
        if (!cluster_shift) break;
        cluster_shift--;
    }
    if (!geometry_found || cluster_count > EXFAT_CLUSTER_MAX ||
        cluster_count > 0xffffffffULL) return false;
    fs.sectors_per_cluster = 1U << cluster_shift;
    fs.cluster_bytes = fs.sectors_per_cluster * EXFAT_SECTOR_BYTES;
    bitmap_bytes = (cluster_count + 7ULL) / 8ULL;
    bitmap_clusters = (bitmap_bytes + fs.cluster_bytes - 1ULL) /
                      fs.cluster_bytes;
    upcase_clusters = (sizeof(exfat_default_upcase) + fs.cluster_bytes - 1ULL) /
                      fs.cluster_bytes;
    root_cluster = 2ULL + bitmap_clusters + upcase_clusters;
    metadata_last = root_cluster;
    if (!bitmap_clusters || !upcase_clusters || root_cluster > cluster_count + 1ULL ||
        metadata_last > 0xffffffffULL) return false;
    memset(&boot, 0, sizeof(boot));
    boot.volume_length = dev->sector_count;
    boot.fat_offset = 2048U;
    boot.fat_length = (u32)fat_length;
    boot.heap_offset = (u32)heap_offset;
    boot.cluster_count = (u32)cluster_count;
    boot.root_cluster = (u32)root_cluster;
    boot.volume_serial = exfat_format_serial(dev);
    boot.revision = 0x0100U;
    boot.volume_flags = 0U;
    boot.bytes_per_sector_shift = 9U;
    boot.sectors_per_cluster_shift = (u8)cluster_shift;
    boot.fat_count = 1U;
    percent = (metadata_last - 1ULL) * 100ULL / cluster_count;
    boot.percent_in_use = (u8)(percent > 100ULL ? 100ULL : percent);
    memset(&fs.boot, 0, sizeof(fs.boot));
    fs.boot = boot;
    fs.root_cluster = boot.root_cluster;
    fs.active_fat = 0;
    boot_region = (u8 *)kmalloc(EXFAT_BOOT_REGION_SECTORS * EXFAT_SECTOR_BYTES);
    upcase_buffer = (u8 *)kmalloc(sizeof(exfat_default_upcase));
    if (!boot_region || !upcase_buffer) {
        kfree(boot_region); kfree(upcase_buffer);
        return false;
    }
    memset(boot_region, 0,
           EXFAT_BOOT_REGION_SECTORS * EXFAT_SECTOR_BYTES);
    {
        static const u8 boot_prefix[11] = {
            0xebU, 0x76U, 0x90U, 'E', 'X', 'F', 'A', 'T', ' ', ' ', ' '
        };
        memcpy(boot_region, boot_prefix, sizeof(boot_prefix));
    }
    exfat_put64(boot_region + 64U, 0ULL);
    exfat_put64(boot_region + 72U, boot.volume_length);
    exfat_put32(boot_region + 80U, boot.fat_offset);
    exfat_put32(boot_region + 84U, boot.fat_length);
    exfat_put32(boot_region + 88U, boot.heap_offset);
    exfat_put32(boot_region + 92U, boot.cluster_count);
    exfat_put32(boot_region + 96U, boot.root_cluster);
    exfat_put32(boot_region + 100U, boot.volume_serial);
    exfat_put16(boot_region + 104U, boot.revision);
    exfat_put16(boot_region + 106U, boot.volume_flags);
    boot_region[108] = boot.bytes_per_sector_shift;
    boot_region[109] = boot.sectors_per_cluster_shift;
    boot_region[110] = boot.fat_count;
    boot_region[111] = 0x80U;
    boot_region[112] = boot.percent_in_use;
    boot_region[510] = 0x55U;
    boot_region[511] = 0xaaU;
    exfat_put32(boot_region + EXFAT_BOOT_CHECKSUM_SECTOR * EXFAT_SECTOR_BYTES,
                exfat_boot_checksum_bytes(boot_region, 11U * EXFAT_SECTOR_BYTES));
    for (u32 at = 4U; at < EXFAT_SECTOR_BYTES; at += 4U)
        exfat_put32(boot_region + EXFAT_BOOT_CHECKSUM_SECTOR * EXFAT_SECTOR_BYTES + at,
                    exfat_le32(boot_region + EXFAT_BOOT_CHECKSUM_SECTOR * EXFAT_SECTOR_BYTES));
    if (!block_write(dev, 0, EXFAT_BOOT_REGION_SECTORS, boot_region) ||
        !block_write(dev, EXFAT_BACKUP_BOOT_LBA, EXFAT_BOOT_REGION_SECTORS,
                     boot_region) ||
        !exfat_format_zero(dev, boot.fat_offset, boot.fat_length)) {
        kfree(boot_region); kfree(upcase_buffer);
        return false;
    }
    if (!exfat_format_fat_entry(dev, boot.fat_offset, boot.fat_length,
                                boot.fat_count, 0U, EXFAT_CLUSTER_EOC) ||
        !exfat_format_fat_entry(dev, boot.fat_offset, boot.fat_length,
                                boot.fat_count, 1U, 0xffffffffU)) {
        kfree(boot_region); kfree(upcase_buffer);
        return false;
    }
    fs.bitmap_cluster = 2U;
    fs.bitmap_length = bitmap_bytes;
    fs.bitmap_no_fat = true;
    fs.upcase_cluster = 2U + (u32)bitmap_clusters;
    fs.upcase_length = sizeof(exfat_default_upcase);
    fs.upcase_no_fat = true;
    fs.upcase_checksum = exfat_upcase_checksum(exfat_default_upcase,
                                               sizeof(exfat_default_upcase));
    /* Only clear the metadata clusters we are about to publish.  Clearing
     * the complete data heap would make formatting proportional to the
     * entire medium and needlessly delay the operation.  Data clusters are
     * already free according to the bitmap and are zeroed on first use. */
    if (!exfat_format_zero(dev, boot.heap_offset,
                           (metadata_last - 1ULL) * fs.sectors_per_cluster)) {
        kfree(boot_region); kfree(upcase_buffer);
        return false;
    }
    for (u32 cluster = 2U; cluster <= (u32)metadata_last; cluster++) {
        if (!exfat_format_fat_entry(dev, boot.fat_offset, boot.fat_length,
                                    boot.fat_count, cluster,
                                    EXFAT_CLUSTER_EOC) ||
            !exfat_format_bitmap_bit(dev, boot.heap_offset,
                                     cluster, true)) {
            kfree(boot_region); kfree(upcase_buffer);
            return false;
        }
    }
    memcpy(upcase_buffer, exfat_default_upcase, sizeof(exfat_default_upcase));
    for (u64 offset = 0; offset < upcase_clusters * fs.cluster_bytes;
         offset += EXFAT_SECTOR_BYTES) {
        memset(sector, 0, sizeof(sector));
        if (offset < sizeof(exfat_default_upcase)) {
            usize amount = sizeof(exfat_default_upcase) - (usize)offset;
            if (amount > sizeof(sector)) amount = sizeof(sector);
            memcpy(sector, upcase_buffer + offset, amount);
        }
        if (!block_write(dev, (u64)exfat_cluster_lba(&fs, fs.upcase_cluster) +
                         offset / EXFAT_SECTOR_BYTES, 1U, sector)) {
            kfree(boot_region); kfree(upcase_buffer);
            return false;
        }
    }
    /* Directory entries are 32-byte records.  Keep the required allocation
     * bitmap and up-case entries adjacent in the root directory; writing the
     * second entry at the next sector would leave an unused entry in between
     * and make the volume invalid to standard exFAT checkers. */
    memset(sector, 0, sizeof(sector));
    exfat_put32(sector + 20U, fs.bitmap_cluster);
    exfat_put64(sector + 24U, bitmap_bytes);
    sector[0] = EXFAT_ENTRY_BITMAP;
    sector[EXFAT_ENTRY_BYTES] = EXFAT_ENTRY_UPCASE;
    exfat_put32(sector + EXFAT_ENTRY_BYTES + 4U, fs.upcase_checksum);
    exfat_put32(sector + EXFAT_ENTRY_BYTES + 20U, fs.upcase_cluster);
    exfat_put64(sector + EXFAT_ENTRY_BYTES + 24U, fs.upcase_length);
    if (!block_write(dev, exfat_cluster_lba(&fs, fs.root_cluster), 1U,
                     sector)) {
        kfree(boot_region); kfree(upcase_buffer);
        return false;
    }
    kfree(boot_region);
    kfree(upcase_buffer);
    return block_flush(dev) && exfat_probe(dev);
}

static int exfat_mount(vfs_fs_type_t *fs_type, block_device_t *dev,
                       vfs_super_t **out_sb, bool read_only)
{
    exfat_fs_t *fs;
    vfs_super_t *sb;
    vfs_node_t *root;
    exfat_node_t *private_root;

    (void)fs_type;
    if (!dev || !out_sb) return VFS_ERR_INVALID_PARAM;
    fs = exfat_new_state(dev);
    if (!fs) return VFS_ERR_BAD_FORMAT;
    fs->read_only = read_only;
    if (!read_only && !exfat_set_volume_dirty(fs, true)) {
        exfat_free_state(fs);
        return VFS_ERR_IO;
    }
    sb = (vfs_super_t *)kmalloc(sizeof(*sb));
    root = (vfs_node_t *)kmalloc(sizeof(*root));
    private_root = (exfat_node_t *)kmalloc(sizeof(*private_root));
    if (!sb || !root || !private_root) {
        kfree(sb); kfree(root); kfree(private_root);
        exfat_free_state(fs);
        return VFS_ERR_NO_MEM;
    }
    memset(sb, 0, sizeof(*sb));
    memset(root, 0, sizeof(*root));
    memset(private_root, 0, sizeof(*private_root));
    private_root->first_cluster = fs->root_cluster;
    private_root->data_length = fs->cluster_bytes;
    private_root->valid_data_length = fs->cluster_bytes;
    root->inode = fs->root_cluster;
    root->type = VFS_TYPE_DIRECTORY;
    root->size = fs->cluster_bytes;
    vfs_node_set_security(root, VFS_UID_SYSTEM, EXFAT_VOLUME_PERMISSIONS);
    root->ref_count = 1;
    root->super = sb;
    root->fs_data = private_root;
    root->ops = &exfat_node_ops;
    sb->fs_type = fs_type;
    sb->dev = dev;
    sb->root_node = root;
    sb->private_data = fs;
    sb->ops = &exfat_super_ops;
    *out_sb = sb;
    return VFS_OK;
}

static const vfs_super_ops_t exfat_super_ops = {
    .unmount = exfat_unmount,
    .sync = exfat_sync,
};

static vfs_fs_type_t exfat_fs_type = {
    .name = "exfat",
    .probe = exfat_probe,
    .label = exfat_read_label_internal,
    .mount = exfat_mount,
    .next = NULL,
};

int exfat_init(void)
{
    return vfs_register_fs(&exfat_fs_type);
}
